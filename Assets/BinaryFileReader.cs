                                    int ConstantSize = ConstantHolder.ConstantSizes[ConstantType];
                                    int ConstantID;

                                    switch (ConstantSize)
                                    {
                                        case 8:
                                            ConstantID = Reader.ReadByte();
                                            break;
                                        case 16:
                                            ConstantID = Reader.ReadInt16();
                                            break;
                                        case 32:
                                            ConstantID = Reader.ReadInt32();
                                            break;
                                        default:
                                            ConstantID = 0;
                                            Debug.LogError($"Constant {ConstantType} has an incorrect constant size: {ConstantSize}");
                                            break;
                                    }

                                    Constant NewConstant = ConstantHolder.GetConstant(ConstantType, ConstantID);

                                    NewCommandInstance.Parameters.Add(NewConstant);
                                    //Debug.Log($"Parameter added to {InAIList.Name} in {Command.Name}: {Constant.Name}");
                                    break;
