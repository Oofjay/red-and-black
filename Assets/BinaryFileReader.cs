    // Reads from the main file the amount of supplied bytes. It decompresses this data, and returns the decompressed data in a stream.
    // Remember to set this returned, decompressed stream as the main stream, so other functions (like ReadPointer) can read from it.
    MemoryStream ReadAndDecompressData(int Size, bool Multiple = false)
    {
        JumpForward(5L); // Decompressed data starts with 0x11, 0x73, then three bytes with the decompressed size
        byte[] CompressedData = Reader.ReadManyBytes(Size - 5);
        MemoryStream CompressedStream = new(CompressedData);

        Inflater CustomInflater = new(true);
        InflaterInputStream InflateStream = new(CompressedStream, CustomInflater);

        //DeflateStream Decompressor = new(CompressedStream, CompressionMode.Decompress);
        MemoryStream DecompressedStream = new();
        InflateStream.CopyTo(DecompressedStream);

        DecompressedStream.Position = 0;

        // Set the file stream's position to the beginning of the next deflate compressed data
        if (Multiple) { CurrentStream.Seek(CustomInflater.TotalIn, SeekOrigin.Current); }

        CompressedStream.Dispose();
        InflateStream.Dispose();
        //Decompressor.Dispose();

        return DecompressedStream;
    }

    // Reads from the main file the amount of supplied bytes. It decompresses this data, and returns the decompressed data in an array.
    byte[] ReadAndDecompressDataToArray(int Size, bool Multiple = false)
    {
        JumpForward(5L); // Decompressed data starts with 0x11, 0x73, then three bytes with the decompressed size
        byte[] CompressedData = Reader.ReadBytes(Size - 5);
        MemoryStream CompressedStream = new(CompressedData);

        Inflater CustomInflater = new(true);
        InflaterInputStream InflateStream = new(CompressedStream, CustomInflater);

        MemoryStream DecompressedStream = new();
        InflateStream.CopyTo(DecompressedStream);

        DecompressedStream.Position = 0;

        // Set the file stream's position to the beginning of the next deflate compressed data
        if (Multiple) { CurrentStream.Seek(CurrentStream.Length - CustomInflater.RemainingInput, SeekOrigin.Begin); }

        byte[] DecompressedArray = DecompressedStream.ToArray();

        CompressedStream.Dispose();
        InflateStream.Dispose();
        DecompressedStream.Dispose();

        return DecompressedArray;
    }

    void ReadUncompressedImage(TextureData InData)
    {
        int TextureSize = InData.SizeAsChannelsWithout1BitAlpha;
        byte[] RawTextureData = new byte[InData.SizeAsChannelsWith1BitAlpha];

        Stream OpenFile = CurrentStream;

        MemoryStream UncompressedData = new(RawTextureData);
        CurrentStream = UncompressedData;
        Reader = new(CurrentStream);

        // Some texture formats have multiple channels in one byte, so we separate them here
        switch (InData.PixelFormat)
        {
            case TexturePixelFormat.RGBA16:
                for (int i = 0; i < TextureSize; ++i)
                {
                    InData.RawTextureData[i] = (byte)ReadBits(5);
                }
                ReadAlphaBits(InData);
                break;
            case TexturePixelFormat.RGB15:
                for (int i = 0; i < TextureSize; ++i)
                {
                    InData.RawTextureData[i] = (byte)ReadBits(5);
                }
                break;
            case TexturePixelFormat.IA8:
            case TexturePixelFormat.I4:
                for (int i = 0; i < TextureSize; ++i)
                {
                    InData.RawTextureData[i] = (byte)ReadBits(4);
                }
                break;
            case TexturePixelFormat.IA4:
                for (int i = 0; i < TextureSize; ++i)
                {
                    InData.RawTextureData[i] = (byte)ReadBits(3);
                }
                ReadAlphaBits(InData);
                break;
            default:
                InData.RawTextureData = RawTextureData;
                break;
        }

        CurrentStream = OpenFile;
        Reader = new(CurrentStream);
    }

    void ReadHuffmanCompressedImage(TextureData InData, ReadMethod Method, int StartIndex = 0)
    {
        // Reserve room for 1 bit alpha if necessary, which will be processed later
        byte[] RawTextureData = new byte[InData.SizeAsChannelsWith1BitAlpha];

        int[] Frequencies = new int[2048];
        int ChannelSize = (Method == ReadMethod.WithLookup) ? InData.NumberOfColours : InData.GetChannelSize();

        // Read the frequencies list
        for (int i = 0; i < ChannelSize; i++)
        {
            Frequencies[i] = ReadBits(8);
        }

        int[,] Nodes = new int[2048, 2];

        // Initialise the tree
        for (int i = 0; i < 2048; i++)
        {
            Nodes[i, 0] = -1;
            Nodes[i, 1] = -1;
        }

        int RootIndex = 0;
        int Sum;
        int MinimumIndex1 = 0;
        int MinimumIndex2 = 0;

        // Find the two smallest frequencies
        int MinimumFrequency1 = 9999;
        int MinimumFrequency2 = 9999;

        for (int i = 0; i < ChannelSize; i++)
        {
            if (Frequencies[i] < MinimumFrequency1)
            {
                if (MinimumFrequency2 < MinimumFrequency1)
                {
                    MinimumFrequency1 = Frequencies[i];
                    MinimumIndex1 = i;
                }
                else
                {
                    MinimumFrequency2 = Frequencies[i];
                    MinimumIndex2 = i;
                }
            }
            else if (Frequencies[i] < MinimumFrequency2)
            {
                MinimumFrequency2 = Frequencies[i];
                MinimumIndex2 = i;
            }
        }

        bool Done = false;

        // Build the tree.
        // For each node in tree, a branch value < 10000 means this branch
        // leads to another node, and the value is the target node's index.
        // A branch value >= 10000 means the branch is a leaf node,
        // and the value is the channel value + 10000.
        while (!Done)
        {
            Sum = Frequencies[MinimumIndex1] + Frequencies[MinimumIndex2];

            if (Sum == 0)
            {
                Sum = 1;
            }

            Frequencies[MinimumIndex1] = 9999;
            Frequencies[MinimumIndex2] = 9999;

            if (Nodes[MinimumIndex1, 0] < 0 && Nodes[MinimumIndex1, 1] < 0)
            {
                Nodes[MinimumIndex1, 0] = MinimumIndex1 + 10000;
                RootIndex = MinimumIndex1;
                Frequencies[MinimumIndex1] = Sum;

                if (Nodes[MinimumIndex2, 0] < 0 && Nodes[MinimumIndex2, 1] < 0)
                {
                    Nodes[MinimumIndex1, 1] = MinimumIndex2 + 10000;
                }
                else
                {
                    Nodes[MinimumIndex1, 1] = MinimumIndex2;
                }
            }
            else if (Nodes[MinimumIndex2, 0] < 0 && Nodes[MinimumIndex2, 1] < 0)
            {
                Nodes[MinimumIndex2, 0] = MinimumIndex2 + 10000;
                RootIndex = MinimumIndex2;
                Frequencies[MinimumIndex2] = Sum;

                if (Nodes[MinimumIndex1, 0] < 0 && Nodes[MinimumIndex1, 1] < 0)
                {
                    Nodes[MinimumIndex2, 1] = MinimumIndex1 + 10000;
                }
                else
                {
                    Nodes[MinimumIndex2, 1] = MinimumIndex1;
                }
            }
            else
            {
                for (RootIndex = 0; Nodes[RootIndex, 0] >= 0 || Nodes[RootIndex, 1] >= 0 || Frequencies[RootIndex] < 9999; RootIndex++) ;

                Frequencies[RootIndex] = Sum;
                Nodes[RootIndex, 0] = MinimumIndex1;
                Nodes[RootIndex, 1] = MinimumIndex2;
            }

            // Find the two smallest Frequencies again for the next iteration
            MinimumFrequency1 = 9999;
            MinimumFrequency2 = 9999;

            for (int i = 0; i < ChannelSize; i++)
            {
                if (Frequencies[i] < MinimumFrequency1)
                {
                    if (MinimumFrequency1 > MinimumFrequency2)
                    {
                        MinimumFrequency1 = Frequencies[i];
                        MinimumIndex1 = i;
                    }
                    else
                    {
                        MinimumFrequency2 = Frequencies[i];
                        MinimumIndex2 = i;
                    }
                }
                else if (Frequencies[i] < MinimumFrequency2)
                {
                    MinimumFrequency2 = Frequencies[i];
                    MinimumIndex2 = i;
                }
            }

            if (MinimumFrequency1 == 9999 || MinimumFrequency2 == 9999)
            {
                Done = true;
            }
        }

        int TextureSize = (Method == ReadMethod.WithLookup || Method == ReadMethod.PerChannel) ? InData.SizeAsPixels : InData.SizeAsChannelsWithout1BitAlpha;

        // Read bits off the bitstring, traverse the tree
        // and write the channel values to dst
        for (int i = StartIndex; i < TextureSize; i++)
        {
            int IndexOrValue = RootIndex;

            while (IndexOrValue < 10000)
            {
                IndexOrValue = Nodes[IndexOrValue, ReadBits(1)];
            }

            RawTextureData[i] = (byte)(IndexOrValue - 10000);
        }

        InData.RawTextureData = RawTextureData;
    }

    void ReadRLECompressedImage(TextureData InData, ReadMethod Method)
    {
        int TextureSize = (Method == ReadMethod.WithLookup) ? InData.SizeAsPixels : InData.SizeAsChannelsWithout1BitAlpha;

        // Reserve room for 1 bit alpha if necessary, which will be processed later
        byte[] RawTextureData = new byte[InData.SizeAsChannelsWith1BitAlpha];

        int BacktrackFieldSize = ReadBits(3);
        int RunLengthFieldSize = ReadBits(3);
        int LiteralBlockSize = ReadBits(4);

        int Fudge = 0;
        int Cost = BacktrackFieldSize + RunLengthFieldSize + LiteralBlockSize + 1;
        while (Cost > 0)
        {
            Cost = Cost - LiteralBlockSize - 1;
            ++Fudge;
        }

        for (int i = 0; i < TextureSize;)
        {
            int LiteralOrRun = ReadBits(1);
            byte Value;

            if (LiteralOrRun == 0) // Literal
            {
                Value = (byte)ReadBits(LiteralBlockSize);
                RawTextureData[i] = Value;
                ++i;
            }
            else // Run
            {
                int BackTrack = i - ReadBits(BacktrackFieldSize) - 1;
                int NumberOfRepeats = ReadBits(RunLengthFieldSize) + Fudge;

                for (int j = BackTrack; j < BackTrack + NumberOfRepeats; ++j)
                {
                    RawTextureData[i] = RawTextureData[j];
                    ++i;
                }

                // The next instruction is always a literal
                Value = (byte)ReadBits(LiteralBlockSize);
                RawTextureData[i] = Value;
                ++i;
            }
        }

        InData.RawTextureData = RawTextureData;
    }

    int ReadBits(int Number)
    {
        int Result = 0;

        for (int i = 0; i < Number; ++i)
        {
            if (BitsRead == 0)
            {
                CurrentByte = Reader.ReadByte();
                CheckBits = 0b10000000;
            }

            int GottenBits = (byte)((CurrentByte & CheckBits) >> (7 - BitsRead));

            if (i > 0)
            {
                Result <<= 1;
            }
            Result |= GottenBits;

            ++BitsRead;
            CheckBits >>= 1;

            if (BitsRead == 8)
            {
                BitsRead = 0;
                CheckBits = 0b10000000;
            }
        }

        return Result;
    }

    // Most compression types store the texture data in subsequent, separate channels, for example RRRGGGBBBAAA.
    // This function combines them into a normal readable format, in this example RGBARGBARGBA.
    void CombineTextureChannels(TextureData InData)
    {
        if (InData.RawTextureData.Length == 0)
        {
            return;
        }

        byte[] ConvertedTextureData = new byte[InData.RawTextureData.Length];
        int ChannelCount = InData.GetNumberOfChannelsWith1BitAlpha();

        int ChannelLength = InData.Width * InData.Height;
        for (int i = 0, j = i * ChannelCount; i < ChannelLength; ++i, j += ChannelCount)
        {
            ConvertedTextureData[j] = InData.RawTextureData[i];
            ConvertedTextureData[j + 1] = InData.RawTextureData[i + ChannelLength];
            if (ChannelCount > 3)
            {
                ConvertedTextureData[j + 2] = InData.RawTextureData[i + ChannelLength * 2];
            }
            if (ChannelCount == 4)
            {
                ConvertedTextureData[j + 3] = InData.RawTextureData[i + ChannelLength * 3];
            }
        }

        InData.RawTextureData = ConvertedTextureData;
    }

    void BuildLookupTable(TextureData InData)
    {
        int NumberOfColours = ReadBits(11);
        int BitsPerPixel = InData.GetBitsPerPixel();
        int[] LookupTable = new int[NumberOfColours];

        for (int i = 0; i < NumberOfColours; ++i)
        {
            LookupTable[i] = ReadBits(BitsPerPixel);
        }

        InData.NumberOfColours = NumberOfColours;
        InData.LookupTable = LookupTable;
    }

    void ReadLookupCompressedImage(TextureData InData)
    {
        int BitsPerColour = GetBitSize(InData.NumberOfColours);
        //int NumberOfChannels = Has1BitAlphaChannel(InData.PixelFormat) ? GetNumberOfChannels(InData.PixelFormat) + 1 : GetNumberOfChannels(InData.PixelFormat);
        int TextureSize = InData.SizeAsChannelsWith1BitAlpha;
        byte[] RawTextureData = new byte[TextureSize];
        int[] LookupTable = InData.LookupTable;

        switch (InData.PixelFormat)
        {
            case TexturePixelFormat.RGBA32:
                for (int i = 0; i < TextureSize; i += 4)
                {
                    int Value = LookupTable[ReadBits(BitsPerColour)];
                    RawTextureData[i] = (byte)((Value & 0xFF000000) >> 24);
                    RawTextureData[i + 1] = (byte)((Value & 0x00FF0000) >> 16);
                    RawTextureData[i + 2] = (byte)((Value & 0x0000FF00) >> 8);
                    RawTextureData[i + 3] = (byte)(Value & 0x000000FF);
                }
                break;
            case TexturePixelFormat.RGBA16:
                for (int i = 0; i < TextureSize; i += 4)
                {
                    int Value = LookupTable[ReadBits(BitsPerColour)];
                    RawTextureData[i] = (byte)((Value & 0b11111_00000_00000_0) >> 11);
                    RawTextureData[i + 1] = (byte)((Value & 0b00000_11111_00000_0) >> 6);
                    RawTextureData[i + 2] = (byte)((Value & 0b00000_00000_11111_0) >> 1);
                    RawTextureData[i + 3] = (byte)(Value & 0b00000_00000_00000_1);
                }
                break;
            case TexturePixelFormat.RGB24:
                for (int i = 0; i < TextureSize; i += 3)
                {
                    int Value = LookupTable[ReadBits(BitsPerColour)];
                    RawTextureData[i] = (byte)((Value & 0xFF0000) >> 16);
                    RawTextureData[i + 1] = (byte)((Value & 0x00FF00) >> 8);
                    RawTextureData[i + 2] = (byte)(Value & 0x0000FF);
                }
                break;
            case TexturePixelFormat.RGB15:
                for (int i = 0; i < TextureSize; i += 3)
                {
                    int Value = LookupTable[ReadBits(BitsPerColour)];
                    RawTextureData[i] = (byte)((Value & 0b11111_00000_00000) >> 10);
                    RawTextureData[i + 1] = (byte)((Value & 0b00000_11111_00000) >> 5);
                    RawTextureData[i + 2] = (byte)(Value & 0b00000_00000_11111);
                }
                break;
            case TexturePixelFormat.IA16:
                for (int i = 0; i < TextureSize; i += 2)
                {
                    int Value = LookupTable[ReadBits(BitsPerColour)];
                    RawTextureData[i] = (byte)((Value & 0xFF00) >> 8);
                    RawTextureData[i + 1] = (byte)(Value & 0x00FF);
                }
                break;
            case TexturePixelFormat.IA8:
                for (int i = 0; i < TextureSize; i += 2)
                {
                    int Value = LookupTable[ReadBits(BitsPerColour)];
                    RawTextureData[i] = (byte)((Value & 0xF0) >> 4);
                    RawTextureData[i + 1] = (byte)(Value & 0x0F);
                    //Debug.Log(Value);
                }
                break;
            case TexturePixelFormat.IA4:
                for (int i = 0; i < TextureSize; i += 2)
                {
                    int Value = LookupTable[ReadBits(BitsPerColour)];
                    RawTextureData[i] = (byte)((Value & 0b1110) >> 2);
                    RawTextureData[i + 1] = (byte)(Value & 0b0001);
                }
                break;
            case TexturePixelFormat.I8:
                for (int i = 0; i < TextureSize; ++i)
                {
                    int Value = LookupTable[ReadBits(BitsPerColour)];
                    RawTextureData[i] = (byte)Value;
                }
                break;
            case TexturePixelFormat.I4:
                for (int i = 0; i < TextureSize; ++i)
                {
                    int Value = LookupTable[ReadBits(BitsPerColour)];
                    RawTextureData[i] = (byte)Value;
                }
                break;
        }

        InData.RawTextureData = RawTextureData;
    }

