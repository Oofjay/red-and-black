    public bool Read3DModel(string FilePath)
    {
        FileName = Path.GetFileNameWithoutExtension(FilePath);
        MainFileStream = File.OpenRead(FilePath);
        CurrentStream = MainFileStream;

        Debug.Log(FilePath);

        if (CurrentStream.Length == 0)
        {
            Debug.LogWarning("File is empty at: " + FilePath);
            return false;
        }

        Reader = new(CurrentStream);

        GoToPointer(); // Hop towards root node

        bool ProcessingNodes = true;

        int NumDLs = 0;

        while (ProcessingNodes)
        {
            Node NewNode = new() { Type = Reader.ReadInt16() };
            JumpForward(2L);

            if (GoToPointer()) // Hop towards node data
            {
                if (NewNode.Type == 0x02) // Position
                {
                    NewNode.Data.PositionX = Reader.ReadSingle();
                    NewNode.Data.PositionY = Reader.ReadSingle();
                    NewNode.Data.PositionZ = Reader.ReadSingle();
                    NewNode.Data.Part = Reader.ReadUInt16();
                    NewNode.Data.MtxIndex1 = Reader.ReadInt16();
                    NewNode.Data.MtxIndex2 = Reader.ReadInt16();
                    NewNode.Data.MtxIndex3 = Reader.ReadInt16();
                    NewNode.Data.DrawDistance = Reader.ReadSingle();
                }
                else if (NewNode.Type == 0x04) // Gun display list
                {
                    uint PrimaryDLPointer = ReadPointer();
                    uint SecondaryDLPointer = ReadPointer();
                    JumpForward(4L); // Jump over "base address" value
                    uint VerticesPointer = ReadPointer();

                    int NumVertices = Reader.ReadUInt16();
                    int ModelType = Reader.ReadUInt16();

                    if (NumVertices * 12 < CurrentStream.Length && GoToPointer(VerticesPointer)) // Hop to gfxvtx
                    {
                        VertexOffset = Vertices.Count;
                        for (int i = 0; i < NumVertices; ++i)
                        {
                            int PositionX = Reader.ReadInt16();
                            int PositionY = Reader.ReadInt16();
                            int PositionZ = Reader.ReadInt16();
                            Vertices.Add(new Vector3(-PositionX, PositionY, PositionZ));

                            VertexData NewVertexData = new() { Flags = Reader.ReadByte() };
                            int ColourIndex = Reader.ReadByte();
                            NewVertexData.ColourIndex = ColourIndex / 4;
                            NewVertexData.ST = new Vector2(Reader.ReadInt16(), Reader.ReadInt16());

                            VertexDataList.Add(NewVertexData);
                        }
                        ReturnFromPointer(); // Go back to node data
                    }

                    for (int i = 0; i < NumVertices; ++i)
                    {
                        Colours.Add(Color.white);
                    }

                    UVs.AddRange(new Vector2[Vertices.Count - UVs.Count]);

                    if (GoToPointer(PrimaryDLPointer)) // Primary (opaque) display list
                    {
                        // The vertex array pointer needs to be passed for 0x04 display lists, since they count
                        // the vertex offset of loaded vertices from the whole file, not from the vertex array.
                        ProcessDisplayList(VerticesPointer);
                        ReturnFromPointer(); // Go back to node data
                    }

                    if (GoToPointer(SecondaryDLPointer)) // Secondary (transparent) display list
                    {
                        // The vertex array pointer needs to be passed for 0x04 display lists, since they count
                        // the vertex offset of loaded vertices from the whole file, not from the vertex array.
                        ProcessDisplayList(VerticesPointer);
                        ReturnFromPointer(); // Go back to node data
                    }
                }
                else if (NewNode.Type == 0x0A) // Bounding box
                {
                    NewNode.Data.HitPart = Reader.ReadInt32();
                    NewNode.Data.XMin = Reader.ReadSingle();
                    NewNode.Data.XMax = Reader.ReadSingle();
                    NewNode.Data.YMin = Reader.ReadSingle();
                    NewNode.Data.YMax = Reader.ReadSingle();
                    NewNode.Data.ZMin = Reader.ReadSingle();
                    NewNode.Data.ZMax = Reader.ReadSingle();
                }
                else if (NewNode.Type == 0x18) // Full display list
                {
                    ++NumDLs;

                    uint PrimaryDLPointer = ReadPointer();
                    uint SecondaryDLPointer = ReadPointer();
                    JumpForward(2L);
                    int ColourTableNumber = Reader.ReadUInt16();
                    uint VerticesPointer = ReadPointer();

                    int NumVertices = Reader.ReadUInt16();
                    int NumMatrices = Reader.ReadInt16();
                    uint RwDataIndex = Reader.ReadUInt16();
                    uint NumColours = Reader.ReadUInt16();

                    // Reserve just enough memory in the lists, so it doesn't have to allocate new memory every so often
                    if (NumVertices > 0)
                    {
                        Vertices.Capacity = NumVertices + Vertices.Count;
                        Colours.Capacity = NumVertices + Colours.Count;
                        UVs.Capacity = NumVertices + UVs.Count;
                    }

                    if (NumVertices * 12 < CurrentStream.Length && GoToPointer(VerticesPointer)) // Hop to gfxvtx
                    {
                        VertexOffset = Vertices.Count;
                        ColourOffset = ColourTable.Count;
                        for (int i = 0; i < NumVertices; ++i)
                        {
                            int PositionX = Reader.ReadInt16();
                            int PositionY = Reader.ReadInt16();
                            int PositionZ = Reader.ReadInt16();
                            Vertices.Add(new Vector3(-PositionX, PositionY, PositionZ));

                            VertexData NewVertexData = new()
                            {
                                Flags = Reader.ReadByte()
                            };
                            int ColourIndex = Reader.ReadByte();
                            NewVertexData.ColourIndex = ColourIndex / 4;
                            NewVertexData.ST = new Vector2(Reader.ReadInt16(), Reader.ReadInt16());

                            VertexDataList.Add(NewVertexData);
                        }

                        int ColourTablePointer = Reader.ReadOffset;
                        // The colour table pointer needs to end with either 0 or 8
                        ColourTablePointer = ((ColourTablePointer + 0x7) | 0x7) ^ 0x7;
                        Reader.Seek(ColourTablePointer, SeekOrigin.Begin);

                        for (int i = 0; i < NumColours; ++i)
                        {
                            Color NewColour = new()
                            {
                                r = Reader.ReadByte(),
                                g = Reader.ReadByte(),
                                b = Reader.ReadByte(),
                                a = Reader.ReadByte()
                            };

                            NewColour.r /= 255;
                            NewColour.g /= 255;
                            NewColour.b /= 255;
                            NewColour.a /= 255;

                            ColourTable.Add(NewColour);
                        }

                        if (ColourTable.Count == 0)
                        {
                            ColourTable.Add(new Color(255, 255, 255, 255));
                        }

                        for (int i = 0; i < NumVertices; ++i)
                        {
                            Colours.Add(ColourTable[VertexDataList[i].ColourIndex]);
                        }
                        ReturnFromPointer(); // Go back to node data
                    }

                    UVs.AddRange(new Vector2[Vertices.Count - UVs.Count]);

                    if (GoToPointer(PrimaryDLPointer)) // Primary (opaque) display list
                    {
                        ProcessDisplayList();
                        ReturnFromPointer(); // Go back to node data
                    }

                    if (GoToPointer(SecondaryDLPointer)) // Secondary (transparent) display list
                    {
                        ProcessDisplayList();
                        ReturnFromPointer(); // Go back to node data
                    }
                }
                ReturnFromPointer(); // Hop back towards node
            }

            NewNode.Parent = ReadPointer();
            NewNode.NextSibling = ReadPointer();
            if (NewNode.NextSibling > 0) 
            {
                SiblingStack.Push(NewNode.NextSibling); 
            }
            NewNode.PreviousSibling = ReadPointer();
            NewNode.Child = ReadPointer();

            ModelData.Nodes.Add(NewNode);

            if (NewNode.Child > 0)
            {
                GoToPointer(NewNode.Child);
            }
            else if (SiblingStack.Count > 0)
            {
                GoToPointer(SiblingStack.Pop());
            }
            else
            {
                ProcessingNodes = false;
                //ReturnFromPointer(); // Go back to model header
            }
        }

        ModelData.TextureIDs = TextureIDs;

        Mesh NewMesh = HelperFunctions.CreateMeshWithSubMeshes(Vertices, Colours, UVs, TriangleIndices, IndexOffsets);
        NewMesh.name = Path.GetFileNameWithoutExtension(FilePath);
        ModelData.Meshes.Add(NewMesh);

        MainFileStream.Dispose();
        Reader.Dispose();
        return ModelData.Nodes.Count > 0;
    }

    public bool ReadLevelBG(string FilePath)
    {
        FileName = Path.GetFileNameWithoutExtension(FilePath);
        MainFileStream = File.OpenRead(FilePath);

        if (MainFileStream.Length == 0)
        {
            return false;
        }

        SetAsCurrentStream(MainFileStream);

        // ---- Section 1 (rooms, portals, lights, visibility commands) ----

        int DecompressedPrimaryDataSize = Reader.ReadInt32();
        int CompressedSection1Size = Reader.ReadInt32();
        int CompressedPrimaryDataSize = Reader.ReadInt32();

        MemoryStream Section1 = ReadAndDecompressData(CompressedPrimaryDataSize);

        SetAsCurrentStream(Section1);

        JumpForward(4L); // Data starts with four null bits

        int RoomCount = 0;
        int PortalCount = 0;

        // -- Room table --
        if (GoToPointer())
        {
            JumpForward(20L); // Skip over room 0 since it's always empty

            while (Reader.ReadOffset != CurrentStream.Length)
            {
                uint GraphicsDataPointer = ReadPointer();

                if (RoomCount != 0)
                {
                    RoomData PreviousRoom = RoomDataList[RoomCount - 1];
                    PreviousRoom.GraphicsDataSize = GraphicsDataPointer - PreviousRoom.GraphicsDataPointer;
                }

                float XPosition = Reader.ReadSingle();
                float YPosition = Reader.ReadSingle();
                float ZPosition = Reader.ReadSingle();
                Vector3 Position = new() { x = XPosition, y = YPosition, z = -ZPosition };

                int MinimumBrightness = Reader.ReadByte();
                int MaximumBrightness = Reader.ReadByte();
                JumpForward(2L);

                if (Reader.PeekByte() == 0)
                {
                    break;
                }

                RoomData CurrentRoomData = new()
                {
                    ID = RoomCount + 1,
                    GraphicsDataPointer = GraphicsDataPointer,
                    Position = Position,
                    MinimumBrightness = MinimumBrightness,
                    MaximumBrightness = MaximumBrightness
                };

                RoomDataList.Add(CurrentRoomData);

                ++RoomCount;
            }

            ReturnFromPointer();
        }

        // -- Portal table --
        if (GoToPointer())
        {

            // Portals
            while (Reader.ReadOffset != CurrentStream.Length)
            {
                int VertexOffset = Reader.ReadInt16();
                int FirstRoom = Reader.ReadInt16();
                int SecondRoom = Reader.ReadInt16();
                JumpForward(2L);

                if (VertexOffset == 0 && FirstRoom == 0 && SecondRoom == 0)
                {
                    break;
                }

                PortalData CurrentPortalData = new()
                {
                    ID = PortalCount,
                    VertexOffset = VertexOffset - 1,
                    FirstRoom = FirstRoom,
                    SecondRoom = SecondRoom,
                };

                if (CurrentPortalData.Flags != 0) { Debug.Log("Portal flags are: " + CurrentPortalData.Flags); }

                PortalDataList.Add(CurrentPortalData);

                ++PortalCount;
            }

            // Portal vertices
            while (Reader.ReadOffset != CurrentStream.Length)
            {
                PortalAdresses.Add(Reader.ReadOffset);

                int VertexCount = Reader.ReadByte();

                if (VertexCount == 0)
                {
                    break;
                }

                JumpForward(3L);

                int TriangleCount = VertexCount - 2;
                int TriangleIndexCount = TriangleCount * 3;

                Mesh NewPortalMesh = new();
                Vector3[] PortalVertices = new Vector3[VertexCount];
                int[] PortalTriangleIndices = new int[TriangleIndexCount * 2];

                for (int i = 0; i < VertexCount; ++i)
                {
                    float XPosition = Reader.ReadSingle();
                    float YPosition = Reader.ReadSingle();
                    float ZPosition = Reader.ReadSingle();
                    PortalVertices[i] = new Vector3() { x = XPosition, y = YPosition, z = -ZPosition };
                }

                for (int i = 0; i < TriangleCount; ++i)
                {
                    PortalTriangleIndices[i * 3] = 2 + i;
                    PortalTriangleIndices[i * 3 + 1] = 1 + i;
                    PortalTriangleIndices[i * 3 + 2] = 0;
                }
                for (int i = 0; i < TriangleCount; ++i) // Reverse the triangles to make the portal model double-sided
                {
                    PortalTriangleIndices[i * 3 + TriangleIndexCount] = 0;
                    PortalTriangleIndices[i * 3 + 1 + TriangleIndexCount] = 1 + i;
                    PortalTriangleIndices[i * 3 + 2 + TriangleIndexCount] = 2 + i;
                }

                NewPortalMesh.vertices = PortalVertices;
                NewPortalMesh.triangles = PortalTriangleIndices;

                PortalMeshes.Add(NewPortalMesh);
            }

            foreach (PortalData CurrentPortal in PortalDataList)
            {
                CurrentPortal.PortalMesh = PortalMeshes[CurrentPortal.VertexOffset];
            }

            ReturnFromPointer();
        }

        // -- Visibility commands table --
        if (GoToPointer())
        {
            while (Reader.ReadOffset != CurrentStream.Length)
            {
                VisibilityCommandData NewVisibilityData = new()
                {
                    ID = Reader.ReadByte(),
                    Length = Reader.ReadByte()
                };

                //Debug.Log(NewVisibilityData.ID.ToString("X"));

                JumpForward(6L);

                int ParameterCount = NewVisibilityData.Length - 1;

                for (int i = 0; i < ParameterCount; ++i)
                {
                    JumpForward(4L);
                    int Argument = Reader.ReadInt32();

                    switch (NewVisibilityData.ID)
                    {
                        case 0x1F:
                        case 0x22:
                        case 0x23:
                        case 0x29:
                            Argument &= 0x00FFFFFF;
                            int PortalNumber = PortalAdresses.IndexOf(Argument);
                            NewVisibilityData.Arguments.Add(PortalNumber);
                            break;
                        default:
                            NewVisibilityData.Arguments.Add(Argument);
                            break;
                    }
                }

                VisibilityDataList.Add(NewVisibilityData);

                if (NewVisibilityData.ID == 0)
                {
                    break;
                }
            }

            ReturnFromPointer();
        }

        uint LightTablePointer = ReadPointer(); // Store this for when we read the lights table at the end

        // ---- Section 2 (texture ID's, not read) ----

        SetAsCurrentStream(MainFileStream);

        Reader.Seek(CompressedSection1Size + 12, SeekOrigin.Begin);

        int DecompressedSection2Size = Reader.ReadInt16();
        int CompressedSection2Size = Reader.ReadInt16();

        // ---- Section 3 ----

        Reader.Seek(CompressedSection2Size, SeekOrigin.Current);

        int DecompressedSection3Size = Reader.ReadInt16();
        int CompressedSection3Size = Reader.ReadInt16();

        MemoryStream Section3 = ReadAndDecompressData(CompressedSection3Size);

        SetAsCurrentStream(Section3);

        JumpForward(12L * RoomCount); // Jump over room bounding boxes
        JumpForward(2L * RoomCount); // Jump over data related to room data size

        int LightCount = 0;

        // -- Room light count --
        for (int i = 0; i < RoomCount; ++i)
        {
            LightCount += Reader.ReadByte();
        }

        SetAsCurrentStream(MainFileStream);

        // ---- Room graphics data ----
        Reader.Seek(CompressedPrimaryDataSize + 0x0C, SeekOrigin.Begin);

        //FileStream RoomBlockStream = new("C:\\Users\\Oofjay\\Desktop\\Temp\\roomdebug.txt", FileMode.Create, FileAccess.Write);
        //RoomBlockWriter = new(RoomBlockStream);
        //RoomBlockWriter.WriteLine("Level " + FileName);
        //RoomBlockWriter.WriteLine(" ");

        int GraphicsDataOffset = Reader.ReadOffset;

        foreach (RoomData CurrentRoom in RoomDataList)
        {
            //RoomBlockWriter.WriteLine("--- Room " + (CurrentRoom.ID + 1).ToString("X") + " ---");
            //RoomBlockWriter.WriteLine(" ");

            if (CurrentRoom.ID != 0)
            {
                ClearAllArrays();

                SetAsCurrentStream(MainFileStream);
                Reader.Seek(GraphicsDataOffset, SeekOrigin.Begin);
            }

            MemoryStream RoomGraphicsData = ReadAndDecompressData((int)CurrentRoom.GraphicsDataSize);
            GraphicsDataOffset += (int)CurrentRoom.GraphicsDataSize;

            SetAsCurrentStream(RoomGraphicsData);

            /*if (CurrentRoom.ID == 51)
            {
                Debug.Log("Room " + (CurrentRoom.ID + 1).ToString("X") + " " + CurrentRoom.GraphicsDataPointer.ToString("X"));

                // --- DEBUG --- 
                byte[] DecompressedSection1 = RoomGraphicsData.ToArray();
                FileStream WriteFileStream = new("C:\\Users\\Oofjay\\Desktop\\Temp\\bg_ear_debug.bin", FileMode.Create, FileAccess.Write);
                WriteFileStream.Write(DecompressedSection1);
                WriteFileStream.Close();
            }*/

            JumpForward(8L);
            uint OpaqueRoomBlockPointer = ReadPointerWithOffset(CurrentRoom.GraphicsDataPointer);
            uint TransparentRoomBlockPointer = ReadPointerWithOffset(CurrentRoom.GraphicsDataPointer);

            if (GoToPointer(OpaqueRoomBlockPointer))
            {
                //RoomBlockWriter.WriteLine("- Opaque blocks -");
                //RoomBlockWriter.WriteLine(" ");

                ProcessRoomBlock(CurrentRoom);
                ReturnFromPointer(); // Go back to room graphics data
            }

            if (GoToPointer(TransparentRoomBlockPointer))
            {
                //RoomBlockWriter.WriteLine("- Transparent blocks -");
                //RoomBlockWriter.WriteLine(" ");

                ProcessRoomBlock(CurrentRoom);
                ReturnFromPointer(); // Go back to room graphics data
            }

            CurrentRoom.TextureIDs.AddRange(TextureIDs);

            Mesh NewMesh = HelperFunctions.CreateMeshWithSubMeshes(Vertices, Colours, UVs, TriangleIndices, IndexOffsets);
            NewMesh.name = Path.GetFileNameWithoutExtension(FilePath);
            CurrentRoom.RoomMesh = NewMesh;
        }

        SetAsCurrentStream(Section1);

        // -- Lights table --
        if (GoToPointer(LightTablePointer))
        {
            for (int i = 0; i < LightCount; ++i)
            {
                LightData NewLight = new();

                NewLight.ID = i;
                NewLight.Room = Reader.ReadInt16();

                byte RG = Reader.ReadByte();
                byte BA = Reader.ReadByte();
                NewLight.Colour = new Color32()
                {
                    r = (byte)(GetUpperNibble(RG) * 16),
                    g = (byte)(GetLowerNibble(RG) * 16),
                    b = (byte)(GetUpperNibble(BA) * 16),
                    a = (byte)(GetLowerNibble(BA) * 16)
                };

                JumpForward(2L);

                byte Sizes = Reader.ReadByte();
                NewLight.Size = GetUpperNibble(Sizes);
                NewLight.RingSize = GetLowerNibble(Sizes);

                int XDirection = Reader.ReadByte();
                int YDirection = Reader.ReadByte();
                int ZDirection = Reader.ReadByte();
                if (XDirection > 127) { XDirection -= 256; }
                if (YDirection > 127) { YDirection -= 256; }
                if (ZDirection > 127) { ZDirection -= 256; }

                NewLight.Direction = new() { x = XDirection, y = YDirection, z = -ZDirection };
                NewLight.Direction /= 127;

                RoomData LightRoom = RoomDataList[NewLight.Room - 1];

                Mesh NewLightMesh = new();
                Vector3[] LightVertices = new Vector3[4];

                // Two triangles per side. Even though a light shines to one side, it displays as double-sided in the editor.
                int[] LightTriangleIndices = new int[12] { 2, 1, 0, 3, 2, 0, 0, 1, 2, 0, 2, 3 };

                for (int j = 0; j < 4; ++j)
                {
                    int XPosition = Reader.ReadInt16();
                    int YPosition = Reader.ReadInt16();
                    int ZPosition = Reader.ReadInt16();
                    Vector3 RelativePosition = new() { x = XPosition, y = YPosition, z = -ZPosition };

                    LightVertices[j] = LightRoom.Position + RelativePosition;
                }

                NewLightMesh.vertices = LightVertices;
                NewLightMesh.triangles = LightTriangleIndices;
                NewLight.LightMesh = NewLightMesh;

                LightDataList.Add(NewLight);
            }

            ReturnFromPointer();
        }

        Reader.Dispose();
        MainFileStream.Dispose();
        Section1.Dispose();
        Section3.Dispose();

        //RoomBlockWriter.Dispose();

        return true;
    }

    public bool ReadPads(string FilePath)
    {
        FileName = Path.GetFileNameWithoutExtension(FilePath);
        MainFileStream = File.OpenRead(FilePath);

        if (MainFileStream.Length == 0)
        {
            return false;
        }

        SetAsCurrentStream(MainFileStream);

        int NumberOfPads = Reader.ReadInt32();
        int NumberOfCoverPads = Reader.ReadInt32();

        uint WaypointPointer = ReadPointer();
        uint WaygroupPointer = ReadPointer();
        uint CoverPadPointer = ReadPointer();

        // -- Pads --
        for (int i = 0; i < NumberOfPads; ++i)
        {
            ushort PadPointer = Reader.ReadUInt16();

            if (GoToPointer(PadPointer))
            {
                PadData NewPad = new() { Number = i, IsCoverPad = false };

                int PadInfo = Reader.ReadInt32();
                int PadFlags = PadInfo >> 14;

                if ((PadFlags & 0b0100_0000_0000_0000_00) > 0) { NewPad.AIDucks = true; }
                if ((PadFlags & 0b0010_0000_0000_0000_00) > 0) { NewPad.AIMovesWhileFalling = true; };
                if ((PadFlags & 0b0001_0000_0000_0000_00) > 0) { NewPad.AICrouches = true; };
                if ((PadFlags & 0b0000_1000_0000_0000_00) > 0) { NewPad.AIDrops = true; };
                if ((PadFlags & 0b0000_0100_0000_0000_00) > 0) { NewPad.AIWalksDirectlyTo = true; };
                if ((PadFlags & 0b0000_0010_0000_0000_00) > 0) { NewPad.AIRidesLift = true; };
                if ((PadFlags & 0b0000_0001_0000_0000_00) > 0) { NewPad.AIWaitsForLift = true; };
                if ((PadFlags & 0b0000_0000_1000_0000_00) > 0) { NewPad.HasBoundingBoxData = true; };
                if ((PadFlags & 0b0000_0000_0100_0000_00) > 0) { NewPad.DirectionAlignInverted = true; };
                if ((PadFlags & 0b0000_0000_0010_0000_00) > 0) { NewPad.DirectionAlignToZ = true; };
                if ((PadFlags & 0b0000_0000_0001_0000_00) > 0) { NewPad.DirectionAlignToY = true; };
                if ((PadFlags & 0b0000_0000_0000_1000_00) > 0) { NewPad.DirectionAlignToX = true; };
                if ((PadFlags & 0b0000_0000_0000_0100_00) > 0) { NewPad.UpAlignInverted = true; };
                if ((PadFlags & 0b0000_0000_0000_0010_00) > 0) { NewPad.UpAlignToZ = true; };
                if ((PadFlags & 0b0000_0000_0000_0001_00) > 0) { NewPad.UpAlignToY = true; };
                if ((PadFlags & 0b0000_0000_0000_0000_10) > 0) { NewPad.UpAlignToX = true; };
                if ((PadFlags & 0b0000_0000_0000_0000_01) > 0) { NewPad.IntegerPosition = true; };

                NewPad.Room = PadInfo & 0x00003FF0; // Not sure what this is, the rooms never get written
                NewPad.LiftNumber = PadInfo & 0x0000000F;

                if (NewPad.IntegerPosition)
                {
                    NewPad.Position.x = Reader.ReadInt16();
                    NewPad.Position.y = Reader.ReadInt16();
                    NewPad.Position.z = -Reader.ReadInt16();
                    JumpForward(2L);
                }
                else
                {
                    NewPad.Position.x = Reader.ReadSingle();
                    NewPad.Position.y = Reader.ReadSingle();
                    NewPad.Position.z = -Reader.ReadSingle();
                }

                if (NewPad.UpAlignToX)
                {
                    NewPad.Up.x = (NewPad.UpAlignInverted ? -1 : 1);
                    NewPad.Up.y = 0;
                    NewPad.Up.z = 0;
                }
                else if (NewPad.UpAlignToY)
                {
                    NewPad.Up.x = 0;
                    NewPad.Up.y = (NewPad.UpAlignInverted ? -1 : 1);
                    NewPad.Up.z = 0;
                }
                else if (NewPad.UpAlignToZ)
                {
                    NewPad.Up.x = 0;
                    NewPad.Up.y = 0;
                    NewPad.Up.z = (NewPad.UpAlignInverted ? 1 : -1);
                }
                else
                {
                    NewPad.Up.x = Reader.ReadSingle();
                    NewPad.Up.y = Reader.ReadSingle();
                    NewPad.Up.z = -Reader.ReadSingle();
                }

                if (NewPad.DirectionAlignToX)
                {
                    NewPad.Direction.x = (NewPad.DirectionAlignInverted ? -1 : 1);
                    NewPad.Direction.y = 0;
                    NewPad.Direction.z = 0;
                }
                else if (NewPad.DirectionAlignToY)
                {
                    NewPad.Direction.x = 0;
                    NewPad.Direction.y = (NewPad.DirectionAlignInverted ? -1 : 1);
                    NewPad.Direction.z = 0;
                }
                else if (NewPad.DirectionAlignToZ)
                {
                    NewPad.Direction.x = 0;
                    NewPad.Direction.y = 0;
                    NewPad.Direction.z = (NewPad.DirectionAlignInverted ? 1 : -1);
                }
                else
                {
                    NewPad.Direction.x = Reader.ReadSingle();
                    NewPad.Direction.y = Reader.ReadSingle();
                    NewPad.Direction.z = -Reader.ReadSingle();
                }

                NewPad.Normal.x = NewPad.Up.y * NewPad.Direction.z - NewPad.Direction.y * NewPad.Up.z;
                NewPad.Normal.y = NewPad.Up.z * NewPad.Direction.x - NewPad.Direction.z * NewPad.Up.x;
                NewPad.Normal.z = NewPad.Up.x * NewPad.Direction.y - NewPad.Direction.x * NewPad.Up.y;

                if (NewPad.HasBoundingBoxData)
                {
                    NewPad.XMin = Reader.ReadSingle();
                    NewPad.XMax = Reader.ReadSingle();
                    NewPad.YMin = Reader.ReadSingle();
                    NewPad.YMax = Reader.ReadSingle();
                    NewPad.ZMin = Reader.ReadSingle();
                    NewPad.ZMax = Reader.ReadSingle();
                }
                else
                {
                    NewPad.XMin = -100;
                    NewPad.YMin = -100;
                    NewPad.ZMin = -100;
                    NewPad.XMax = 100;
                    NewPad.YMax = 100;
                    NewPad.ZMax = 100;
                }

                PadDataList.Add(NewPad);

                ReturnFromPointer();
            }
        }

        // -- Waypoints --
        if (GoToPointer(WaypointPointer))
        {
            int WaypointID = 0;

            while (Reader.ReadOffset != CurrentStream.Length)
            {
                uint WaypointNumber = Reader.ReadUInt32();

                if (WaypointNumber == 0xFFFFFFFF)
                {
                    break;
                }

                Waypoint NewWaypoint = new();

                NewWaypoint.ID = WaypointID;
                NewWaypoint.ParentPadID = (int)WaypointNumber;
                PadDataList[(int)WaypointNumber].PadWaypoint = NewWaypoint;

                // Neighbours
                if (GoToPointer())
                {
                    while (Reader.ReadOffset != CurrentStream.Length)
                    {
                        uint NeighbourNumber = Reader.ReadUInt32();

                        if (NeighbourNumber == 0xFFFFFFFF)
                        {
                            break;
                        }

                        WaypointNeighbour NewNeighbour = new();

                        NewNeighbour.NeighbourID = (int)(NeighbourNumber & 0x0FFF);
                        if ((NeighbourNumber & 0x4000) > 0) { NewNeighbour.MoveOutwardsOnly = true; }
                        if ((NeighbourNumber & 0x8000) > 0) { NewNeighbour.MoveInwardsOnly = true; }

                        NewWaypoint.Neighbours.Add(NewNeighbour);
                    }

                    ReturnFromPointer();
                }

                NewWaypoint.WaygroupID = Reader.ReadInt32();
                JumpForward(4L);

                Waypoints.Add(NewWaypoint);

                ++WaypointID;
            }

            ReturnFromPointer();
        }

        // -- Waygroups --
        if (GoToPointer(WaygroupPointer))
        {
            int WaygroupCounter = 0;

            while (Reader.ReadOffset != CurrentStream.Length)
            {
                uint NeighbourPointer = Reader.ReadUInt32();

                if (NeighbourPointer == 0x0000)
                {
                    break;
                }

                Waygroup NewWaygroup = new();
                NewWaygroup.ID = WaygroupCounter;

                // Neighbours
                if (GoToPointer(NeighbourPointer))
                {
                    while (Reader.ReadOffset != CurrentStream.Length)
                    {
                        uint NeighbourNumber = Reader.ReadUInt32();

                        if (NeighbourNumber == 0xFFFFFFFF)
                        {
                            break;
                        }

                        WaygroupNeighbour NewNeighbour = new();

                        NewNeighbour.NeighbourID = (int)(NeighbourNumber & 0x00FF);
                        if ((NeighbourNumber & 0x4000) > 0) { NewNeighbour.MoveOutwardsOnly = true; }
                        if ((NeighbourNumber & 0x8000) > 0) { NewNeighbour.MoveInwardsOnly = true; }

                        NewWaygroup.Neighbours.Add(NewNeighbour);
                    }

                    ReturnFromPointer();
                }

                // Waypoints
                if (GoToPointer())
                {
                    while (Reader.ReadOffset != CurrentStream.Length)
                    {
                        uint WaypointNumber = Reader.ReadUInt32();

                        if (WaypointNumber == 0xFFFFFFFF)
                        {
                            break;
                        }

                        Waypoint FoundWaypoint = Waypoints[(int)WaypointNumber];

                        FoundWaypoint.ParentWaygroup = NewWaygroup;
                        NewWaygroup.Waypoints.Add(FoundWaypoint);
                    }

                    ReturnFromPointer();
                }

                JumpForward(4L);

                ++WaygroupCounter;
                Waygroups.Add(NewWaygroup);
            }

            ReturnFromPointer();
        }

        // -- Cover pads --
        if (GoToPointer(CoverPadPointer))
        {
            for (int i = 0; i < NumberOfCoverPads; ++i)
            {
                PadData NewCoverPad = new() { Number = i, IsCoverPad = true };

                NewCoverPad.Position.x = Reader.ReadSingle();
                NewCoverPad.Position.y = Reader.ReadSingle();
                NewCoverPad.Position.z = -Reader.ReadSingle();

                NewCoverPad.Direction.x = Reader.ReadSingle();
                NewCoverPad.Direction.y = Reader.ReadSingle();
                NewCoverPad.Direction.z = -Reader.ReadSingle();

                NewCoverPad.CoverFlags = Reader.ReadInt32();

                CoverPadDataList.Add(NewCoverPad);
            }

            ReturnFromPointer();
        }

        foreach (Waypoint CurrentWaypoint in Waypoints)
        {
            foreach (WaypointNeighbour CurrentNeighbour in CurrentWaypoint.Neighbours)
            {
                CurrentNeighbour.LinkedWaypoint = Waypoints.Find(x => x.ID == CurrentNeighbour.NeighbourID);
            }
        }

        foreach (Waygroup CurrentWaygroup in Waygroups)
        {
            foreach (WaygroupNeighbour CurrentNeighbour in CurrentWaygroup.Neighbours)
            {
                CurrentNeighbour.LinkedWaygroup = Waygroups.Find(x => x.ID == CurrentNeighbour.NeighbourID);
            }
        }

        Reader.Dispose();
        MainFileStream.Dispose();

        return true;
    }

