                    case 0x04:
                        NewAIList.Type = AIListType.Character;
                        break;
                    case 0x0C:
                        NewAIList.Type = AIListType.Cutscene;
                        break;
                    case 0x10:
                        NewAIList.Type = AIListType.Background;
                        break;
                    case 0x14:
                        NewAIList.Type = AIListType.Environmental;
                        break;
