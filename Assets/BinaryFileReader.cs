    }

    int AddBytesTogether(byte[] ByteString)
    {
        int Result = ByteString[0];
        for (int i = 0; i < ByteString.Length - 1; ++i)
        {
            Result = (Result << 8) | ByteString[i + 1];
        }
        return Result;
    }
