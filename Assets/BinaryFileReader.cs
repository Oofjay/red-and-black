                for (int i = 0, j = 0; i < TextureSize; i += 3, ++j)
                {
                    int Value = LookupTable[LookupIndices[j]];
                    RawTextureData[i] = (byte)((Value & 0xFF0000) >> 16);
                    RawTextureData[i + 1] = (byte)((Value & 0x00FF00) >> 8);
                    RawTextureData[i + 2] = (byte)(Value & 0x0000FF);
                }
                break;
            case TexturePixelFormat.RGB15:
                for (int i = 0, j = 0; i < TextureSize; i += 3, ++j)
                {
                    int Value = LookupTable[LookupIndices[j]];
                    RawTextureData[i] = (byte)((Value & 0b11111_00000_00000) >> 10);
                    RawTextureData[i + 1] = (byte)((Value & 0b00000_11111_00000) >> 5);
                    RawTextureData[i + 2] = (byte)(Value & 0b00000_00000_11111);
                }
                break;
            case TexturePixelFormat.IA16:
                for (int i = 0, j = 0; i < TextureSize; i += 2, ++j)
                {
                    int Value = LookupTable[LookupIndices[j]];
                    RawTextureData[i] = (byte)((Value & 0xFF00) >> 8);
                    RawTextureData[i + 1] = (byte)(Value & 0x00FF);
                }
                break;
            case TexturePixelFormat.IA8:
                for (int i = 0, j = 0; i < TextureSize; i += 2, ++j)
                {
                    //Debug.Log($"{LookupIndices[j]}, {LookupTable.Length}");
                    int Value = LookupTable[LookupIndices[j]];
                    RawTextureData[i] = (byte)((Value & 0xF0) >> 4);
                    RawTextureData[i + 1] = (byte)(Value & 0x0F);
                    //Debug.Log(Value);
                }
                break;
            case TexturePixelFormat.IA4:
                for (int i = 0, j = 0; i < TextureSize; i += 2, ++j)
                {
                    int Value = LookupTable[LookupIndices[j]];
                    RawTextureData[i] = (byte)((Value & 0b1110) >> 1);
                    RawTextureData[i + 1] = (byte)(Value & 0b0001);
                }
                break;
            case TexturePixelFormat.I8:
                for (int i = 0; i < TextureSize; ++i)
                {
                    int Value = LookupTable[LookupIndices[i]];
                    RawTextureData[i] = (byte)Value;
                }
                break;
            case TexturePixelFormat.I4:
                for (int i = 0; i < TextureSize; ++i)
                {
                    int Value = LookupTable[LookupIndices[i]];
                    RawTextureData[i] = (byte)Value;
                }
                break;
        }

        InData.RawTextureData = RawTextureData;
    }

    int GetBitSize(int NumberOfColours)
    {
        int BitSize = 0;

        --NumberOfColours;

        while (NumberOfColours > 0)
        {
            NumberOfColours >>= 1;
            ++BitSize;
        }

        return BitSize;

    }

    // If a texture format has a 1 bit alpha channel, this function should be called to read the alpha bits and tack them on at the end.
    void ReadAlphaBits(TextureData InData)
    {
        int TextureSize = InData.SizeAsPixels;
        byte[] RawTextureData = InData.RawTextureData;

        for (int i = InData.SizeAsChannelsWithout1BitAlpha; i < TextureSize; ++i)
        {
            RawTextureData[i] = (byte)ReadBits(1);
        }
    }

    void BlurTexture(TextureData InData, int BlurMethod)
    {
        byte[] RawTextureData = InData.RawTextureData;
        int Width = InData.Width;
        int Height = InData.GetNumberOfChannels() * InData.Height;
        int ChannelSize = InData.GetChannelSize();

        if (RawTextureData.Length == 0)
        {
            return;
        }

        for (int y = 0; y < Height; ++y)
        {
            for (int x = 0; x < Width; ++x)
            {
                int CurrentPixel = RawTextureData[y * Width + x] + ChannelSize * 2;
                int LeftPixel = x > 0 ? RawTextureData[y * Width + x - 1] : 0;
                int Above = y > 0 ? RawTextureData[(y - 1) * Width + x] : 0;
                int AboveLeftPixel = x > 0 && y > 0 ? RawTextureData[(y - 1) * Width + x - 1] : 0;

                switch (BlurMethod)
                {
                    case 0:
                        RawTextureData[y * Width + x] = (byte)((CurrentPixel + LeftPixel) % ChannelSize);
                        break;
                    case 1:
                        RawTextureData[y * Width + x] = (byte)((CurrentPixel + Above) % ChannelSize);
                        break;
                    case 2:
                        RawTextureData[y * Width + x] = (byte)((CurrentPixel + AboveLeftPixel) % ChannelSize);
                        break;
                    case 3:
                        RawTextureData[y * Width + x] = (byte)((CurrentPixel + (LeftPixel + Above - AboveLeftPixel)) % ChannelSize);
                        break;
                    case 4:
                        RawTextureData[y * Width + x] = (byte)((CurrentPixel + (Above - AboveLeftPixel) / 2 + LeftPixel) % ChannelSize);
                        break;
                    case 5:
                        RawTextureData[y * Width + x] = (byte)((CurrentPixel + (LeftPixel - AboveLeftPixel) / 2 + Above) % ChannelSize);
                        break;
                    case 6:
                        RawTextureData[y * Width + x] = (byte)((CurrentPixel + ((LeftPixel + Above) / 2)) % ChannelSize);
                        break;
                }
            }
        }
    }

    LanguageString ReadLanguageString(int LanguageNumber)
    {
        if ((LanguageNumber & 0xFFFF) == 0xFFFF)
        {
            return null;
        }

        int BankID = (LanguageNumber & 0x0000FE00) >> 9;
        int StringID = LanguageNumber & 0x000001FF;

        if (BankID == 0 || BankID >= LanguageFileHolder.LanguageFiles.Count)
        {
            return null;
        }

        return LanguageFileHolder.LanguageFiles[BankID].LanguageStrings[StringID];
    }

    void JumpForward(long Offset)
    {
        Reader.Seek((int)Offset, SeekOrigin.Current);
    }

    uint ReadPointer()
    {
        uint Pointer = Reader.ReadUInt32();
        return Pointer &= 0x00FFFFFF;
    }

    uint ReadPointerWithOffset(uint Offset)
    {
        uint Pointer = Reader.ReadUInt32();
        Pointer &= 0x00FFFFFF;

        if (Pointer != 0)
        {
            Pointer -= Offset;
        }

        return Pointer;
    }

    bool GoToPointer()
    {
        uint Pointer = ReadPointer();

        if (Pointer == 0)
        {
            return false;
        }    
        else
        {
            PointerStack.Push((uint)Reader.ReadOffset);
            //Debug.Log("Try to jump to address: " + Pointer.ToString("X"));
            Reader.Seek((int)Pointer, SeekOrigin.Begin);
            return true;
        }

    }

