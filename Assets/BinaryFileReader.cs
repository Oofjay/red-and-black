                        NewProp = new() { InternalID = PropID, Type = PropType.Hoverprop };

                        ReadCommonPropAttributes(ObjectInfo, NewProp);
                        NewProp.HoverType = ConstantHolder.GetConstant("HOVTYPE", Reader.ReadByte());
                        JumpForward(63L);

                        Props.Add(NewProp);
                        VisibleProps.Add(NewProp);
                        ++PropID;
                        break;
                    case 0x36: // Fan
                        NewProp = new() { InternalID = PropID, Type = PropType.Fan };

                        ReadCommonPropAttributes(ObjectInfo, NewProp);
                        JumpForward(8L);
                        NewProp.MaxSpeed = Reader.ReadSingle();
                        JumpForward(4L);
                        NewProp.Acceleration = Reader.ReadSingle();
                        NewProp.On = System.Convert.ToBoolean(Reader.ReadInt32());

                        Props.Add(NewProp);
                        VisibleProps.Add(NewProp);
                        ++PropID;
                        break;
                    case 0x37: // Hovercar
                        NewProp = new() { InternalID = PropID, Type = PropType.Hovercar };

                        ReadCommonPropAttributes(ObjectInfo, NewProp);

                        NewOffset = new() { OffsetPropID = PropID };
                        NewOffset.AIListID = Reader.ReadInt32();
                        JumpForward(56L);

                        Offsets.Add(NewOffset);
                        Props.Add(NewProp);
                        VisibleProps.Add(NewProp);
                        ++PropID;
                        break;
                    case 0x38: // Pad effect
                        NewProp = new() { InternalID = PropID, Type = PropType.Effect };

                        NewProp.Effect = ConstantHolder.GetConstant("PADEFFECT", Reader.ReadInt32());
                        NewProp.ParentPad = DataHolder.Pads[Reader.ReadInt32()];

                        Props.Add(NewProp);
                        VisibleProps.Add(NewProp);
                        ++PropID;
                        break;
                    case 0x39: // Hovercopter
                        NewProp = new() { InternalID = PropID, Type = PropType.Hovercopter };

                        ReadCommonPropAttributes(ObjectInfo, NewProp);

                        NewOffset = new() { OffsetPropID = PropID };
                        NewOffset.AIListID = Reader.ReadInt32();
                        JumpForward(136L);

                        Offsets.Add(NewOffset);
                        Props.Add(NewProp);
                        VisibleProps.Add(NewProp);
                        ++PropID;
                        break;
                    case 0x3A: // Mine
                        NewProp = new() { InternalID = PropID, Type = PropType.Mine };

                        ReadCommonPropAttributes(ObjectInfo, NewProp);

                        NewProp.WeaponType = ConstantHolder.GetConstant("WEAPON", Reader.ReadByte());
                        JumpForward(11L);

                        Props.Add(NewProp);
                        VisibleProps.Add(NewProp);
                        ++PropID;
                        break;
                    case 0x3B: // Escalator step
                        NewProp = new() { InternalID = PropID, Type = PropType.EscalatorStep };

                        ReadCommonPropAttributes(ObjectInfo, NewProp);
                        JumpForward(16L);

                        Props.Add(NewProp);
                        VisibleProps.Add(NewProp);
                        ++PropID;
                        break;
                    default:
                        Debug.LogError("Syntax error: wrong object type at: " + Reader.ReadOffset);
                        break;
                }
            }

            foreach (Prop CurrentProp in Props)
            {
                if (CurrentProp.IsAttachedToCharacter)
                {
                    Prop CurrentCharacter = Characters.Find(x => x.CharacterID == CurrentProp.ParentPropID);

                    if (CurrentCharacter != null)
                    {
                        CurrentCharacter.SubProps.Add(CurrentProp);
                        CurrentProp.ParentProp = CurrentCharacter;
                    }
                    else
                    {
                        Debug.LogWarning($"SubProp refers to an invalid character");
                    }
                }
                else if (CurrentProp.IsAttachedToOtherProp)
                {
                    Prop ParentProp = Props[CurrentProp.InternalID + CurrentProp.ParentPropID];

                    if (CurrentProp != null)
                    {
                        ParentProp.SubProps.Add(CurrentProp);
                        CurrentProp.ParentProp = ParentProp;
                    }
                    else
                    {
                        Debug.LogWarning($"SubProp refers to an invalid parent prop");
                    }
                }
                else if (CurrentProp.ParentPad != null) // Prop is not attached to any pad
                {
                    if (CurrentProp.ParentPad.PadProp != null) { Debug.Log($"Prop is being attached to pad that already has a prop"); }

                    CurrentProp.ParentPad.AddProp(CurrentProp);
                }
                else
                {
                    CurrentProp.IsGlobal = true;
                }
            }

            // Assign all the tags to the objective conditions that refer to those tags
            foreach (Objective IteratedObjective in Objectives)
            {
                foreach (ObjectiveCondition IteratedCondition in IteratedObjective.Conditions)
                {
                    switch (IteratedCondition.Type)
                    {
                        case ConditionType.DestroyObject:
                        case ConditionType.CollectObject:
                        case ConditionType.DepositObject:
                        case ConditionType.HolographObject:
                            IteratedCondition.AddNewTag(Tags.Find(x => x.TagID == IteratedCondition.TagID));
                            break;
                        default:
                            continue;
                    }
                }
            }

            ReturnFromPointer();
        }

        // -- Paths --
        if (GoToPointer())
        {
            while (Reader.ReadOffset != CurrentStream.Length)
            {
                uint PathPointer = Reader.ReadUInt32();

                if (PathPointer == 0)
                {
                    break;
                }

                GuardPath NewPath = new();

                NewPath.ID = Reader.ReadByte();
                NewPath.Name = $"Path {NewPath.ID:X}";

                int PathFlags = Reader.ReadByte();
                NewPath.IsCircularPath = (PathFlags & 1) != 0;
                NewPath.IsFlyingPath = (PathFlags & 2) != 0;
                JumpForward(2L);

                if (GoToPointer(PathPointer))
                {
                    while (Reader.ReadOffset != CurrentStream.Length)
                    {
                        int PadNumber = Reader.ReadInt32();

                        if (PadNumber == -1)
                        {
                            break;
                        }

                        NewPath.AddPad(DataHolder.Pads[PadNumber]);
                    }

                    ReturnFromPointer();
                }

                Paths.Add(NewPath);
            }

            ReturnFromPointer();
        }

