                                        BitFlag MatchedBitFlag = StageFlags.GetBitFlag(Bits);

                                        if (MatchedBitFlag == null) // Bit flag doesn't exist yet
                                        {
                                            BitFlag NewBitFlag = new() { Bits = Bits, Name = $"Stage flag {StageFlags.Count + 1}: {Bits:X}", Constant = "STAGEFLAG_" + Bits.ToString("X") };
                                            BitFlags.Add(NewBitFlag);
                                            StageFlags.Add(NewBitFlag);

                                            NewBitFlag.ConnectedAICommands.Add(new() { CommandInstance = NewCommandInstance, ParameterID = NewCommandInstance.Parameters.Count });
                                        }
                                        else
                                        {
                                            BitFlags.Add(MatchedBitFlag);

                                            MatchedBitFlag.ConnectedAICommands.Add(new() { CommandInstance = NewCommandInstance, ParameterID = NewCommandInstance.Parameters.Count });
                                        }
                                    }
                                    else if (BitFlagType == "LOCKFLAG")
                                    {
                                        int Bits = Reader.ReadByte();

                                        BitFlag MatchedBitFlag = LockFlags.GetBitFlag(Bits);

                                        if (MatchedBitFlag == null) // Bit flag doesn't exist yet
                                        {
                                            BitFlag NewBitFlag = new() { Bits = Bits, Name = $"Lock flag {LockFlags.Count + 1}", Constant = "LOCKFLAG_" + Bits.ToString("X") };
                                            BitFlags.Add(NewBitFlag);
                                            LockFlags.Add(NewBitFlag);

                                            NewBitFlag.ConnectedAICommands.Add(new() { CommandInstance = NewCommandInstance, ParameterID = NewCommandInstance.Parameters.Count });
                                        }
                                        else
                                        {
                                            BitFlags.Add(MatchedBitFlag);

                                            MatchedBitFlag.ConnectedAICommands.Add(new() { CommandInstance = NewCommandInstance, ParameterID = NewCommandInstance.Parameters.Count });
                                        }
                                    }
                                    else
                                    {
                                        int Bits;
                                        int BitFlagSize = GameBitFlagHolder.BitFlagSizes[BitFlagType];

                                        switch (BitFlagSize)
                                        {
                                            case 8:
                                                Bits = Reader.ReadByte();
                                                break;
                                            case 16:
                                                Bits = Reader.ReadInt16();
                                                break;
                                            case 32:
                                                Bits = Reader.ReadInt32();
                                                break;
                                            default:
                                                Bits = 0;
                                                Debug.LogError($"BitFlag {BitFlagType} has an incorrect constant size: {BitFlagSize}");
                                                break;
                                        }

                                        BitFlags = GameBitFlagHolder.GetBitFlags(BitFlagType, Bits);
                                    }

                                    NewCommandInstance.Parameters.Add(BitFlags);
                                    //Debug.Log($"Parameter added to {InAIList.Name} in {Command.Name}: {BitFlags.Count}");
                                    break;
                                case "null":
                                    JumpForward(1L);
                                    break;
                                default:
                                    NewCommandInstance.Parameters.Add(new object());
                                    Debug.LogError($"Syntax error: Parameter {CurrentParameter.ClassType} not recognized at: {Reader.ReadOffset:X}");
                                    break;
                            }
                        }
                    }

                    AILists.Add(NewAIList);

                    ReturnFromPointer();
                }
            }

            ReturnFromPointer();
        }

        foreach (PropOffsetHolder CurrentOffset in Offsets)
        {
            Prop CurrentProp = Props[CurrentOffset.OffsetPropID];

            if (CurrentProp.Type == PropType.ConditionalScenery)
            {
                if (CurrentOffset.TriggerPropOffset != 0) { CurrentProp.TriggerProp = Props[CurrentProp.InternalID + CurrentOffset.TriggerPropOffset]; }
                if (CurrentOffset.UnexplodedPropOffset != 0) { CurrentProp.UnexplodedProp = Props[CurrentProp.InternalID + CurrentOffset.UnexplodedPropOffset]; }
                if (CurrentOffset.ExplodedPropOffset != 0) { CurrentProp.ExplodedProp = Props[CurrentProp.InternalID + CurrentOffset.ExplodedPropOffset]; }
            }
            else if (CurrentProp.Type == PropType.BlockedPath)
            {
                CurrentProp.PathBlockingProp = Props[CurrentProp.InternalID + CurrentOffset.PathBlockingPropOffset];
            }
            else if (CurrentProp.Type == PropType.Door)
            {
                if (CurrentOffset.LinkedDoorOffset != 0) { CurrentProp.LinkedDoor = Props[CurrentProp.InternalID + CurrentOffset.LinkedDoorOffset]; }
            }
            else if (CurrentProp.Type == PropType.LinkGuns)
            {
                Prop Weapon1 = Props[CurrentProp.InternalID + CurrentOffset.LinkedGunOffset1];
                Prop Weapon2 = Props[CurrentProp.InternalID + CurrentOffset.LinkedGunOffset2];

                CurrentProp.LinkedWeapon1 = Weapon1;
                CurrentProp.LinkedWeapon2 = Weapon2;

                Weapon1.LinkedWeapon = Weapon2;
                Weapon2.LinkedWeapon = Weapon1;
            }
            else if (CurrentProp.Type == PropType.Lift)
            {
                if (CurrentOffset.LiftDoor1Offset != 0) { CurrentProp.LiftDoor1 = Props[CurrentProp.InternalID + CurrentOffset.LiftDoor1Offset]; }
                if (CurrentOffset.LiftDoor2Offset != 0) { CurrentProp.LiftDoor2 = Props[CurrentProp.InternalID + CurrentOffset.LiftDoor2Offset]; }
                if (CurrentOffset.LiftDoor3Offset != 0) { CurrentProp.LiftDoor3 = Props[CurrentProp.InternalID + CurrentOffset.LiftDoor3Offset]; }
                if (CurrentOffset.LiftDoor4Offset != 0) { CurrentProp.LiftDoor4 = Props[CurrentProp.InternalID + CurrentOffset.LiftDoor4Offset]; }
            }
            else if (CurrentProp.Type == PropType.LiftDoor)
            {
                Prop Lift = Props[CurrentProp.InternalID + CurrentOffset.LiftStopLiftOffset];
                Lift.LiftStops.Add(CurrentProp);

                CurrentProp.LiftStopLift = Lift;
                CurrentProp.LiftStopDoor = Props[CurrentProp.InternalID + CurrentOffset.LiftStopDoorOffset];
            }
            else if (CurrentProp.Type == PropType.Tag)
            {
                Prop TaggedProp = Props[CurrentProp.InternalID + CurrentOffset.TaggedPropOffset];

                CurrentProp.TaggedProp = TaggedProp;
                TaggedProp.AttachedTag = CurrentProp;
            }
            else if (CurrentProp.Type == PropType.Rename)
            {
                Prop ObjectWithNewName = Props[CurrentProp.InternalID + CurrentOffset.RenameObjectOffset];

                ObjectWithNewName.RenameObject = CurrentProp;
                CurrentProp.ParentProp = ObjectWithNewName;
            }
            else if (CurrentProp.Type == PropType.Character || CurrentProp.Type == PropType.Hovercar || CurrentProp.Type == PropType.Hovercopter)
            {
                if (CurrentProp.Type == PropType.Character && CurrentOffset.ChairTagID != -1)
                {
                    Prop Tag = Tags.Find(x => x.TagID == CurrentOffset.ChairTagID);

                    CurrentProp.Chair = Tag;
                    Tag.ConnectedCharacter = CurrentProp;
                }

                //Debug.Log(CurrentOffset.AIListID.ToString("X"));

                AIList CharacterAIList = AILists.Find(x => x.ID == CurrentOffset.AIListID);

                if (CharacterAIList == null)
                {
                    CharacterAIList = DataHolder.GlobalAILists.Find(x => x.ID == CurrentOffset.AIListID);
                }

                //Debug.Log(CharacterAIList == null);

                CharacterAIList.ConnectedProps.Add(CurrentProp);
                CurrentProp.AIList = CharacterAIList;
            }
        }

        foreach (AIListOffsetHolder CurrentOffset in AIListOffsets)
        {
            AICommandInstance CurrentCommandInstance = CurrentOffset.CommandInstance;

            int AIListID = (int)CurrentCommandInstance.Parameters[CurrentOffset.ParameterIndex];

            AIList FoundAIList = AILists.Find(x => x.ID == AIListID);

            if (FoundAIList == null)
            {
                FoundAIList = DataHolder.GlobalAILists.Find(x => x.ID == AIListID);
            }

            CurrentCommandInstance.Parameters[CurrentOffset.ParameterIndex] = FoundAIList;
        }

        Reader.Dispose();
        MainFileStream.Dispose();

        return true;
    }

    public bool ReadCollision(string FilePath)
    {
        FileName = Path.GetFileNameWithoutExtension(FilePath);
        MainFileStream = File.OpenRead(FilePath);
        SetAsCurrentStream(MainFileStream);

        int RoomCount = Reader.ReadInt32();
        List<uint> RoomPointers = new();

        // Read all room pointers first. The empty rooms have pointers that are the same as the next room.
        // There is also a pointer for the end of the file at the end of this list of pointers.
        for (int i = 0; i <= RoomCount; ++i)
        {
            RoomPointers.Add(Reader.ReadUInt32());
        }

        for (int i = 0; i < RoomCount; ++i)
        {
            // The room pointer is the same as the next pointer. Thus, the room is empty and has no collision
            if (RoomPointers[i] == RoomPointers[i + 1])
            {
                continue;
            }

            CollisionData NewCollision = new();
            NewCollision.CollisionRoom = DataHolder.GetRoom(i);

            List<Vector3> Vertices = new();
            List<Color32> Colours = new();
            List<int> TriangleIndices = new();

            if (GoToPointer(RoomPointers[i])) // Go to room data
            {
                int TileID = 0;

                // Process each tile until we hit the pointer of the next room (or the end of the file)
                while (Reader.ReadOffset != RoomPointers[i + 1])
                {
                    Tile NewTile = new() { ID = TileID };

                    int VertexCount = Reader.ReadInt16();

                    int TriangleCount = VertexCount - 2;

                    NewTile.MinTriangleIndex = TriangleIndices.Count;
                    NewTile.MaxTriangleIndex = TriangleIndices.Count + TriangleCount * 3 - 1;

                    int TileFlags = Reader.ReadInt16();

                    if ((TileFlags & 0x0001) > 0) { NewTile.Floor1 = true; }
                    if ((TileFlags & 0x0002) > 0) { NewTile.Floor2 = true; }
                    if ((TileFlags & 0x0004) > 0) { NewTile.Wall = true; }
                    if ((TileFlags & 0x0008) > 0) { NewTile.BlockSight = true; }
                    if ((TileFlags & 0x0010) > 0) { NewTile.BlockGunfire = true; }
                    if ((TileFlags & 0x0020) > 0) { NewTile.LiftFloor = true; }
                    if ((TileFlags & 0x0040) > 0) { NewTile.Ladder = true; }
                    if ((TileFlags & 0x0080) > 0) { NewTile.RampWall = true; }
                    if ((TileFlags & 0x0100) > 0) { NewTile.Slope = true; }
                    if ((TileFlags & 0x0200) > 0) { NewTile.Underwater = true; }
                    if ((TileFlags & 0x0400) > 0) { NewTile.Flag0400 = true; }
                    if ((TileFlags & 0x0800) > 0) { NewTile.AICrouches = true; }
                    if ((TileFlags & 0x1000) > 0) { NewTile.AIDucks = true; }
                    if ((TileFlags & 0x2000) > 0) { NewTile.AlwaysAscend = true; }
                    if ((TileFlags & 0x4000) > 0) { NewTile.DieOnTouch = true; }
                    if ((TileFlags & 0x8000) > 0) { NewTile.PlayerOnlyLadder = true; }

                    NewTile.FloorType = Reader.ReadInt16();

                    JumpForward(6L); // Jump over all the bounding box data, the editor doesn't need that

                    int ColourInt = Reader.ReadInt16();
                    byte Red = (byte)((ColourInt >> 8 & 0x00F) * 17);
                    byte Green = (byte)((ColourInt >> 4 & 0x00F) * 17);
                    byte Blue = (byte)((ColourInt & 0x00F) * 17);
                    Color32 FloorColour = new(Red, Green, Blue, 255);

                    int VertexOffset = Vertices.Count;

                    for (int j = 0; j < VertexCount; ++j)
                    {
                        int XPosition = Reader.ReadInt16();
                        int YPosition = Reader.ReadInt16();
                        int ZPosition = Reader.ReadInt16();

                        Vertices.Add(new Vector3(XPosition, YPosition, -ZPosition));
                        Colours.Add(FloorColour);
                    }

                    for (int j = 0; j < TriangleCount; ++j)
                    {
                        TriangleIndices.Add(2 + j + VertexOffset);
                        TriangleIndices.Add(1 + j + VertexOffset);
                        TriangleIndices.Add(0 + VertexOffset);
                    }

                    NewCollision.Tiles.Add(NewTile);

                    ++TileID;
                }

                ReturnFromPointer();
            }

            Mesh NewMesh = new();

            NewMesh.vertices = Vertices.ToArray();
            NewMesh.triangles = TriangleIndices.ToArray();
            NewMesh.colors32 = Colours.ToArray();

            NewCollision.CollisionMesh = NewMesh;

            CollisionDataList.Add(NewCollision);
        }

        Reader.Dispose();
        MainFileStream.Dispose();

        return true;
    }

    public Texture2D ReadTexture(string FilePath)
    {
        FileName = Path.GetFileNameWithoutExtension(FilePath);
        MainFileStream = File.OpenRead(FilePath);
        CurrentStream = MainFileStream;

        MainFileStream = File.OpenRead(FilePath);
        CurrentStream = MainFileStream;

        if (CurrentStream.Length == 0)
        {
            return new Texture2D(0, 0);
        }

        Reader = new(CurrentStream);

        TextureData NewTextureData = new();

        byte TextureInformation = Reader.ReadByte();
        NewTextureData.HasCustomDetailLevels = ((TextureInformation & 0b1000_0000) >> 7) == 1;
        NewTextureData.DetailLevels = TextureInformation & 63;
        if (NewTextureData.DetailLevels > 5) { NewTextureData.DetailLevels = 5; }

        if ((TextureInformation & 64) != 0) // Texture is zlib compressed
        {
            //Debug.Log(Path.GetFileName(FilePath) + " is zlib with LODs: " + NewTextureData.DetailLevels + ", included in file: " + NewTextureData.HasCustomDetailLevels);
            NewTextureData.PixelFormat = (TexturePixelFormat)Reader.ReadByte();
            int NumberOfColours = Reader.ReadByte();
            ++NumberOfColours;

            short[] Palette = new short[NumberOfColours];

            for (int i = 0; i < NumberOfColours; ++i)
            {
                Palette[i] = Reader.ReadInt16();
            }

            NewTextureData.Width = Reader.ReadByte();
            NewTextureData.Height = Reader.ReadByte();

            NewTextureData.DetailLevels = 0; // TEMPORARY

            byte[] RawTextureData = NewTextureData.GenerateRawTextureData();

            int ImagesToRead = NewTextureData.HasCustomDetailLevels ? NewTextureData.DetailLevels : 0;
            for (int DetailLevel = 0; DetailLevel <= ImagesToRead; ++DetailLevel)
            {
                if (Reader.ReadOffset == CurrentStream.Length)
                {
                    NewTextureData.DetailLevels = DetailLevel;
                    break;
                }
                // The width and height of the current mip (detail level)
                int Width;
                int Height;

                if (DetailLevel == 0)
                {
                    Width = NewTextureData.Width;
                    Height = NewTextureData.Height;
                }
                else
                {
                    Width = Reader.ReadByte();
                    Height = Reader.ReadByte();
                }
                //Debug.Log(Width + " " + Height);

                byte[] Indices = ReadAndDecompressDataToArray((int)(CurrentStream.Length - Reader.ReadOffset), true);

                int ImageSize = Width * Height * NewTextureData.GetNumberOfChannelsWith1BitAlpha();
                switch (NewTextureData.PixelFormat)
                {
                    case TexturePixelFormat.RGBA16_CI8:
                        for (int i = 0, j = 0; i < ImageSize; i += 4, ++j)
                        {
                            int Index = Indices[j];
                            short Value = Palette[Index];

                            RawTextureData[i]     = (byte)((Value & 0b11111_00000_00000_0) >> 11);
                            RawTextureData[i + 1] = (byte)((Value & 0b00000_11111_00000_0) >> 6);
                            RawTextureData[i + 2] = (byte)((Value & 0b00000_00000_11111_0) >> 1);
                            RawTextureData[i + 3] = (byte)(Value  & 0b00000_00000_00000_1);
                        }
                        break;
                    case TexturePixelFormat.RGBA16_CI4:
                        for (int i = 0, j = 0; i < ImageSize; i += 8, ++j)
                        {
                            int BothIndices = Indices[j];
                            int Index1 = (BothIndices & 0xF0) >> 4;
                            int Index2 = BothIndices & 0x0F;

                            short Value1 = Palette[Index1];
                            RawTextureData[i]     = (byte)((Value1 & 0b11111_00000_00000_0) >> 11);
                            RawTextureData[i + 1] = (byte)((Value1 & 0b00000_11111_00000_0) >> 6);
                            RawTextureData[i + 2] = (byte)((Value1 & 0b00000_00000_11111_0) >> 1);
                            RawTextureData[i + 3] = (byte)(Value1  & 0b00000_00000_00000_1);

                            if (i + 4 == ImageSize) { break; }

                            short Value2 = Palette[Index2];
                            RawTextureData[i + 4] = (byte)((Value2 & 0b11111_00000_00000_0) >> 11);
                            RawTextureData[i + 5] = (byte)((Value2 & 0b00000_11111_00000_0) >> 6);
                            RawTextureData[i + 6] = (byte)((Value2 & 0b00000_00000_11111_0) >> 1);
                            RawTextureData[i + 7] = (byte)(Value2  & 0b00000_00000_00000_1);
                        }
                        break;
                    case TexturePixelFormat.IA16_CI8:
                        for (int i = 0, j = 0; i < ImageSize; i += 2, ++j)
                        {
                            int Index = Indices[j];
                            short Value = Palette[Index];

                            RawTextureData[i]     = (byte)((Value & 0xFF00) >> 8);
                            RawTextureData[i + 1] = (byte)(Value & 0x00FF);
                        }
                        break;
                    case TexturePixelFormat.IA16_CI4:
                        for (int i = 0, j = 0; i < ImageSize; i += 4, ++j)
                        {
                            int BothIndices = Indices[j];
                            int Index1 = (BothIndices & 0xF0) >> 4;
                            int Index2 = BothIndices & 0x0F;

                            short Value1 = Palette[Index1];
                            RawTextureData[i]     = (byte)((Value1 & 0xFF00) >> 8);
                            RawTextureData[i + 1] = (byte)(Value1 & 0x00FF);

                            if (i + 2 == ImageSize) { break; }

                            short Value2 = Palette[Index2];
                            RawTextureData[i + 2] = (byte)((Value2 & 0xFF00) >> 8);
                            RawTextureData[i + 3] = (byte)(Value2 & 0x00FF);
                        }
                        break;
                }

                NewTextureData.Palette = Palette;
                NewTextureData.RawTextureData = RawTextureData;
            }
        }
        else
        {
            NewTextureData.DetailLevels = 1; // TEMPORARY
            for (int i = 0; i < NewTextureData.DetailLevels; ++i)
            {
                int ImageInformation = AddBytesTogether(Reader.ReadBytes(3));
                NewTextureData.PixelFormat = (TexturePixelFormat)((ImageInformation & 0xF00000) >> 20);
                NewTextureData.Width = (ImageInformation & 0x0FF000) >> 12;
                NewTextureData.Height = (ImageInformation & 0x000FF0) >> 4;
                TextureCompressionFormat CompressionFormat = (TextureCompressionFormat)(ImageInformation & 0x00000F);

                int BlurMethod;

                //Debug.Log(Path.GetFileName(FilePath) + " " + NewTextureData.PixelFormat + " " + CompressionFormat);

                switch (CompressionFormat)
                {
                    case TextureCompressionFormat.Uncompressed:
                    case TextureCompressionFormat.Uncompressed2:
                        ReadUncompressedImage(NewTextureData);
                        break;
                    case TextureCompressionFormat.Huffman:
                        ReadHuffmanCompressedImage(NewTextureData, ReadMethod.Normal);

                        if (NewTextureData.Has1BitAlphaChannel())
                        {
                            ReadAlphaBits(NewTextureData);
                        }

                        if (NewTextureData.GetNumberOfChannels() != 1)
                        {
                            CombineTextureChannels(NewTextureData);
                        }
                        break;
                    case TextureCompressionFormat.HuffmanPerHChannel:
                        int NumberOfChannels = NewTextureData.GetNumberOfChannels();

                        for (int j = 0; j < NumberOfChannels; ++j)
                        {
                            ReadHuffmanCompressedImage(NewTextureData, ReadMethod.PerChannel, j * NewTextureData.SizeAsPixels);
                        }

                        if (NewTextureData.Has1BitAlphaChannel())
                        {
                            ReadAlphaBits(NewTextureData);
                        }

                        if (NewTextureData.GetNumberOfChannels() != 1)
                        {
                            CombineTextureChannels(NewTextureData);
                        }
                        break;
                    case TextureCompressionFormat.RLE:
                        ReadRLECompressedImage(NewTextureData, ReadMethod.Normal);

                        if (NewTextureData.Has1BitAlphaChannel())
                        {
                            ReadAlphaBits(NewTextureData);
                        }

                        if (NewTextureData.GetNumberOfChannels() != 1)
                        {
                            CombineTextureChannels(NewTextureData);
                        }
                        break;
                    case TextureCompressionFormat.Lookup:
                        BuildLookupTable(NewTextureData);

                        ReadLookupCompressedImage(NewTextureData);
                        break;
                    case TextureCompressionFormat.HuffmanLookup:
                        BuildLookupTable(NewTextureData);

                        ReadHuffmanCompressedImage(NewTextureData, ReadMethod.WithLookup);

                        ReadLookupCompressedImageFromData(NewTextureData);
                        break;
                    case TextureCompressionFormat.RLELookup:
                        BuildLookupTable(NewTextureData);

                        ReadRLECompressedImage(NewTextureData, ReadMethod.WithLookup);

                        ReadLookupCompressedImageFromData(NewTextureData);
                        break;
                    case TextureCompressionFormat.HuffmanBlur:
                        BlurMethod = ReadBits(3);
                        ReadHuffmanCompressedImage(NewTextureData, ReadMethod.Normal);

                        BlurTexture(NewTextureData, BlurMethod);

                        if (NewTextureData.Has1BitAlphaChannel())
                        {
                            ReadAlphaBits(NewTextureData);
                        }

                        if (NewTextureData.GetNumberOfChannels() != 1)
                        {
                            CombineTextureChannels(NewTextureData);
                        }
                        break;
                    case TextureCompressionFormat.RLEBlur:
                        BlurMethod = ReadBits(3);

                        ReadRLECompressedImage(NewTextureData, ReadMethod.Normal);

                        BlurTexture(NewTextureData, BlurMethod);

                        if (NewTextureData.Has1BitAlphaChannel())
                        {
                            ReadAlphaBits(NewTextureData);
                        }

                        if (NewTextureData.GetNumberOfChannels() != 1)
                        {
                            CombineTextureChannels(NewTextureData);
                        }
                        break;
                }
            }
        }

        CurrentStream.Dispose();
        Reader.Dispose();

        if (NewTextureData.RawTextureData.Length > 0)
        {
            Texture2D NewTexture = ConvertTextureData(NewTextureData);
            if (NewTexture != null) NewTexture.name = Path.GetFileNameWithoutExtension(FilePath);

            return NewTexture;
        }
        else
        {
            return new Texture2D(0, 0);
        }
    }

    // Process the display list at the pointer that is currently in the stream.
    // Goes through all the display list commands until it encounters the B8 commmand.

    // For 0x04 display list nodes, the VerticesPointer argument is passed. Since when loading vertices
    // for a 0x04 display list the offset into the vertex data is from the whole file, not the vertex
    // array, we need to pass the vertex array pointer, so it can subtract that from the offset to
    // get the position of the currently loaded vertices relative to the vertex array.
    void ProcessDisplayList(uint VerticesPointer = 0)
    {
        bool ProcessingDL = true;
        uint VertArrOffset;
        int CurrentTextureWidth = 0;
        int CurrentTextureHeight = 0;
        int[] LoadedVertices = new int[32];

        while (ProcessingDL)
        {
            int CommandType = Reader.ReadByte();
            switch (CommandType)
            {
                case 0x04: // load vertices
                    int NumVertsLoaded = GetUpperNibble(Reader.ReadByte());
                    NumVertsLoaded += 1; // This number is base 0 for some reason
                    JumpForward(2L); // jump over the "number of bytes to load"
                    VertArrOffset = Reader.ReadUInt32();
                    VertArrOffset &= 0xFFFFFF; // Get rid of the first byte, which is irrelevant, which leaves us with the offset into the vertex array
                    VertArrOffset -= VerticesPointer; // in the case of a 04 display list, the offset to the loaded vertices is relative to the whole file, not the vertex array
                    VertArrOffset /= 12; // Then, divide the offset by the number of bytes per vertex, which converts the offset from bytes to amount of vertices

                    if (VertArrOffset > Vertices.Count)
                    {
                        Debug.LogWarning("Vertex array offset is bigger than the amount of vertices");
                        break;
                    }

                    for (int i = 0; i < NumVertsLoaded; ++i)
                    {
                        LoadedVertices[i] = i + (int)VertArrOffset + VertexOffset;
                    }
                    break;
                case 0xB1: // draw 4 tris
                    byte[] IndexBytes = Reader.ReadBytes(7);

                    //TriangleIndices.Capacity += 12;

                    int Tri1Point1 = GetLowerNibble(IndexBytes[6]);
                    int Tri1Point2 = GetUpperNibble(IndexBytes[6]);
                    int Tri1Point3 = GetLowerNibble(IndexBytes[2]);
                    int Tri2Point1 = GetLowerNibble(IndexBytes[5]);
                    int Tri2Point2 = GetUpperNibble(IndexBytes[5]);
                    int Tri2Point3 = GetUpperNibble(IndexBytes[2]);
                    int Tri3Point1 = GetLowerNibble(IndexBytes[4]);
                    int Tri3Point2 = GetUpperNibble(IndexBytes[4]);
                    int Tri3Point3 = GetLowerNibble(IndexBytes[1]);
                    int Tri4Point1 = GetLowerNibble(IndexBytes[3]);
                    int Tri4Point2 = GetUpperNibble(IndexBytes[3]);
                    int Tri4Point3 = GetUpperNibble(IndexBytes[1]);

                    bool DrawTri1 = Tri1Point1 != 0 || Tri1Point2 != 0 || Tri1Point3 != 0;
                    bool DrawTri2 = Tri2Point1 != 0 || Tri2Point2 != 0 || Tri2Point3 != 0;
                    bool DrawTri3 = Tri3Point1 != 0 || Tri3Point2 != 0 || Tri3Point3 != 0;
                    bool DrawTri4 = Tri4Point1 != 0 || Tri4Point2 != 0 || Tri4Point3 != 0;

                    List<int> VerticesToConvert = new(12);

                    int VertexIndex1;
                    int VertexIndex2;
                    int VertexIndex3;

                    // Caution: Unity uses a clockwise system to draw triangles.
                    // N64 uses counter-clockwise, so the indices go from 3 to 1.
                    if (DrawTri1)
                    {
                        VertexIndex1 = LoadedVertices[Tri1Point3];
                        VertexIndex2 = LoadedVertices[Tri1Point2];
                        VertexIndex3 = LoadedVertices[Tri1Point1];

                        TriangleIndices.Add(VertexIndex1);
                        TriangleIndices.Add(VertexIndex2);
                        TriangleIndices.Add(VertexIndex3);
                        if (VertexDataList[VertexIndex1].UVsCalculated == false) VerticesToConvert.Add(VertexIndex1);
                        if (VertexDataList[VertexIndex2].UVsCalculated == false) VerticesToConvert.Add(VertexIndex2);
                        if (VertexDataList[VertexIndex3].UVsCalculated == false) VerticesToConvert.Add(VertexIndex3);
                    }
                    if (DrawTri2)
                    {
                        VertexIndex1 = LoadedVertices[Tri2Point3];
                        VertexIndex2 = LoadedVertices[Tri2Point2];
                        VertexIndex3 = LoadedVertices[Tri2Point1];

                        TriangleIndices.Add(VertexIndex1);
                        TriangleIndices.Add(VertexIndex2);
                        TriangleIndices.Add(VertexIndex3);
                        if (VertexDataList[VertexIndex1].UVsCalculated == false) VerticesToConvert.Add(VertexIndex1);
                        if (VertexDataList[VertexIndex2].UVsCalculated == false) VerticesToConvert.Add(VertexIndex2);
                        if (VertexDataList[VertexIndex3].UVsCalculated == false) VerticesToConvert.Add(VertexIndex3);
                    }
                    if (DrawTri3)
                    {
                        VertexIndex1 = LoadedVertices[Tri3Point3];
                        VertexIndex2 = LoadedVertices[Tri3Point2];
                        VertexIndex3 = LoadedVertices[Tri3Point1];

                        TriangleIndices.Add(VertexIndex1);
                        TriangleIndices.Add(VertexIndex2);
                        TriangleIndices.Add(VertexIndex3);
                        if (VertexDataList[VertexIndex1].UVsCalculated == false) VerticesToConvert.Add(VertexIndex1);
                        if (VertexDataList[VertexIndex2].UVsCalculated == false) VerticesToConvert.Add(VertexIndex2);
                        if (VertexDataList[VertexIndex3].UVsCalculated == false) VerticesToConvert.Add(VertexIndex3);
                    }
                    if (DrawTri4)
                    {
                        VertexIndex1 = LoadedVertices[Tri4Point3];
                        VertexIndex2 = LoadedVertices[Tri4Point2];
                        VertexIndex3 = LoadedVertices[Tri4Point1];

                        TriangleIndices.Add(VertexIndex1);
                        TriangleIndices.Add(VertexIndex2);
                        TriangleIndices.Add(VertexIndex3);
                        if (VertexDataList[VertexIndex1].UVsCalculated == false) VerticesToConvert.Add(VertexIndex1);
                        if (VertexDataList[VertexIndex2].UVsCalculated == false) VerticesToConvert.Add(VertexIndex2);
                        if (VertexDataList[VertexIndex3].UVsCalculated == false) VerticesToConvert.Add(VertexIndex3);
                    }

                    ConvertSTtoUV(VerticesToConvert, CurrentTextureWidth, CurrentTextureHeight);
                    break;
                case 0xB8: // end display list
                    ProcessingDL = false;
                    break;
                case 0xC0: // load texture (GE/PD only)
                    IndexOffsets.Add(TriangleIndices.Count); // With every new texture, we need a new submesh, so add the starting triangle index of this submesh
                    JumpForward(5L); // Jump over most things for now

                    int TextureID = Reader.ReadUInt16();
                    TextureID &= 0x0FFF; // Remove the first nibble of this 16-bit int, which isn't relevant

                    if (!DataHolder.Materials.ContainsKey(TextureID))
                    {
                        Debug.LogWarning($"Texture not recognized: {TextureID}");
                        TextureID = 0;
                    }

                    TextureIDs.Add(TextureID);

                    Texture CurrentTexture = DataHolder.Materials[TextureID].GetTexture("_MainTex");
                    CurrentTextureWidth = CurrentTexture.width;
                    CurrentTextureHeight = CurrentTexture.height;
                    break;
                case 0xFD: // load texture from model file
                    IndexOffsets.Add(TriangleIndices.Count); // With every new texture, we need a new submesh, so add the starting triangle index of this submesh
                    TextureIDs.Add(0);
                    JumpForward(7L);
                    break;
                default:
                    JumpForward(7L); // Jump over all bytes (except the first one, which already has been processed by CommandType)
                    break;
            }
        }
    }

    private Texture2D ConvertTextureData(TextureData InData)
    {
        Texture2D NewTexture = new(InData.Width, InData.Height, InData.GetUnityTextureFormat(), InData.DetailLevels + 1, false);
        byte[] RawTextureData = InData.RawTextureData;

        int TextureSize = RawTextureData.Length;

        byte[] UnityTextureData = NewTexture.GetRawTextureData();

        //Debug.Log($"Texture size: {RawTextureData.Length}, {UnityTextureData.Length}, {InData.Width * InData.Height * InData.GetNumberOfChannelsWith1BitAlpha()}, {NewTexture.mipmapCount}");

        switch (InData.PixelFormat)
        {
            case TexturePixelFormat.RGBA32:
                for (int i = 0; i < TextureSize; ++i)
                {
                    UnityTextureData[i] = RawTextureData[i];
                }
                break;
            case TexturePixelFormat.RGB24:
                for (int i = 0; i < TextureSize; ++i)
                {
                    UnityTextureData[i] = RawTextureData[i];
                }
                break;
            case TexturePixelFormat.RGB15:
                for (int i = 0; i < TextureSize; ++i)
                {
                    UnityTextureData[i] = (byte)(RawTextureData[i] * 8);
                }
                break;
            case TexturePixelFormat.IA16:
            case TexturePixelFormat.IA16_CI8:
            case TexturePixelFormat.IA16_CI4:
                for (int i = 0, j = 0; i < TextureSize; i += 2, j += 4)
                {
                    byte Intensity = RawTextureData[i];

                    UnityTextureData[j]     = Intensity;
                    UnityTextureData[j + 1] = Intensity;
                    UnityTextureData[j + 2] = Intensity;
                    UnityTextureData[j + 3] = RawTextureData[i + 1];
                }
                break;
            case TexturePixelFormat.IA8:
                for (int i = 0, j = 0; i < TextureSize; i += 2, j += 4)
                {
                    byte Intensity = (byte)(RawTextureData[i] * 17);
                    byte Alpha = (byte)(RawTextureData[i + 1] * 17);

                    UnityTextureData[j]     = Intensity;
                    UnityTextureData[j + 1] = Intensity;
                    UnityTextureData[j + 2] = Intensity;
                    UnityTextureData[j + 3] = Alpha;
                }
                break;
            case TexturePixelFormat.IA4:
                for (int i = 0, j = 0; i < TextureSize; i += 2, j += 4)
                {
                    byte Intensity = (byte)(RawTextureData[i] * 17);
                    byte Alpha = (byte)(RawTextureData[i + 1] * 255);

                    UnityTextureData[j] = Intensity;
                    UnityTextureData[j + 1] = Intensity;
                    UnityTextureData[j + 2] = Intensity;
                    UnityTextureData[j + 3] = Alpha;
                }
                break;
            case TexturePixelFormat.I8:
                for (int i = 0, j = 0; i < TextureSize; ++i, j += 3)
                {
                    byte Intensity = RawTextureData[i];

                    UnityTextureData[j]     = Intensity;
                    UnityTextureData[j + 1] = Intensity;
                    UnityTextureData[j + 2] = Intensity;
                }
                break;
            case TexturePixelFormat.I4:
                for (int i = 0, j = 0; i < TextureSize; ++i, j += 3)
                {
                    byte Intensity = (byte)(RawTextureData[i] * 17);

                    UnityTextureData[j]     = Intensity;
                    UnityTextureData[j + 1] = Intensity;
                    UnityTextureData[j + 2] = Intensity;
                }
                break;
            case TexturePixelFormat.RGBA16:
            case TexturePixelFormat.RGBA16_CI8:
            case TexturePixelFormat.RGBA16_CI4:
                for (int i = 0; i < TextureSize; i += 4)
                {
                    UnityTextureData[i]     = (byte)(RawTextureData[i] * 8);
                    UnityTextureData[i + 1] = (byte)(RawTextureData[i + 1] * 8);
                    UnityTextureData[i + 2] = (byte)(RawTextureData[i + 2] * 8);
                    UnityTextureData[i + 3] = (byte)(RawTextureData[i + 3] * 255);
                }
                break;
            default:
                return null;
        }

        /*while (UnityTextureData.Count < NewTexture.GetRawTextureData().Length)
        {
            UnityTextureData.Add(0);
        }*/

        NewTexture.LoadRawTextureData(UnityTextureData);
        NewTexture.Apply(false, true);
        return NewTexture;
    }

    private void ProcessRoomBlock(RoomData CurrentRoom)
    {
        while (Reader.ReadOffset < CurrentStream.Length)
        {
            //RoomBlockWriter.WriteLine($"Block: {CurrentStream.Position:X}");
            int Type = Reader.ReadByte();
            JumpForward(3L);
            uint NextRoomBlock = ReadPointerWithOffset(CurrentRoom.GraphicsDataPointer);
            uint ChildRoomBlock = 0;

            if (NextRoomBlock != 0)
            {
                SiblingStack.Push(NextRoomBlock);
                //Debug.Log(CurrentRoom.ID + " " + CurrentRoom.GraphicsDataPointer.ToString("X"));
                //Debug.Log($"Room {CurrentRoom.ID} has a \"next\" block");
            }

            if (Type == 0) // Geometry block
            {
                uint DisplayListPointer = ReadPointerWithOffset(CurrentRoom.GraphicsDataPointer);
                uint VerticesPointer = ReadPointerWithOffset(CurrentRoom.GraphicsDataPointer);
                uint ColoursPointer = ReadPointerWithOffset(CurrentRoom.GraphicsDataPointer);

                int VertexCount = ((int)ColoursPointer - (int)VerticesPointer) / 12;
                int ColourCount = ((int)DisplayListPointer - (int)ColoursPointer) / 4;

                if (GoToPointer(VerticesPointer))
                {
                    VertexOffset = Vertices.Count;
                    ColourOffset = ColourTable.Count;

                    for (int i = 0; i < VertexCount; ++i)
                    {
                        int PositionX = Reader.ReadInt16();
                        int PositionY = Reader.ReadInt16();
                        int PositionZ = Reader.ReadInt16();
                        Vertices.Add(new Vector3(PositionX, PositionY, -PositionZ));

                        VertexData NewVertexData = new() { Flags = Reader.ReadByte() };
                        int ColourIndex = Reader.ReadByte();
                        NewVertexData.ColourIndex = ColourIndex / 4;
                        NewVertexData.ST = new Vector2(Reader.ReadInt16(), Reader.ReadInt16());

                        VertexDataList.Add(NewVertexData);
                    }

                    ReturnFromPointer(); // Go back to room block
                }

                UVs.AddRange(new Vector2[Vertices.Count - UVs.Count]);

                if (GoToPointer(ColoursPointer))
                {
                    for (int i = 0; i < ColourCount; ++i)
                    {
                        Color NewColour = new()
                        {
                            r = Reader.ReadByte(),
                            g = Reader.ReadByte(),
                            b = Reader.ReadByte(),
                            a = Reader.ReadByte()
                        };

                        NewColour.r /= 255;
                        NewColour.g /= 255;
                        NewColour.b /= 255;
                        NewColour.a /= 255;

                        ColourTable.Add(NewColour);
                    }

                    for (int i = 0; i < VertexCount; ++i)
                    {
                        Colours.Add(ColourTable[VertexDataList[i].ColourIndex]);
                    }

                    ReturnFromPointer(); // Go back to room block
                }

                if (GoToPointer(DisplayListPointer))
                {
                    ProcessDisplayList();
                    ReturnFromPointer(); // Go back to room block
                }
                //RoomBlockWriter.WriteLine($"Block type: {Type}");
                //RoomBlockWriter.WriteLine($"Child: {ChildRoomBlock:X}");
                //RoomBlockWriter.WriteLine($"Sibling: {NextRoomBlock:X}");
            }
            else // Display order block
            {
                ChildRoomBlock = ReadPointerWithOffset(CurrentRoom.GraphicsDataPointer);
                uint CoordinatePointer = ReadPointerWithOffset(CurrentRoom.GraphicsDataPointer);

                if (GoToPointer(CoordinatePointer))
                {
                    Vector3 Position = new() { x = Reader.ReadSingle(), y = Reader.ReadSingle(), z = Reader.ReadSingle() };
                    Vector3 Direction = new() { x = Reader.ReadSingle(), y = Reader.ReadSingle(), z = Reader.ReadSingle() };

                    //RoomBlockWriter.WriteLine($"Block type: {Type}");
                    //RoomBlockWriter.WriteLine($"Child: {ChildRoomBlock:X}");
                    //RoomBlockWriter.WriteLine($"Sibling: {NextRoomBlock:X}");
                    //RoomBlockWriter.WriteLine($"Position: {Position}");
                    //RoomBlockWriter.WriteLine($"Direction: {Direction}");

                    ReturnFromPointer();
                }
            }

            //RoomBlockWriter.WriteLine($" ");

            if (ChildRoomBlock != 0)
            {
                GoToPointerWithoutStack(ChildRoomBlock);
            }
            else if (SiblingStack.Count > 0)
            {
                GoToPointerWithoutStack(SiblingStack.Pop());
            }
            else
            {
                SiblingStack.Clear();
                break;
            }
        }
    }

    private void ConvertSTtoUV(List<int> VertexIndices, int TextureWidth, int TextureHeight)
    {
        int NumVertexIndices = VertexIndices.Count;
        int NumVertexData = VertexDataList.Count;

        for (int i = 0; i < NumVertexIndices; ++i)
        {
            int VertexIndex = VertexIndices[i];
            if (VertexIndex >= NumVertexData)
            {
                continue;
            }

            VertexData CurrentVertexData = VertexDataList[VertexIndex];
            if (CurrentVertexData.UVsCalculated == false) // If the UV hasn't been calculated yet
            {

                Vector2 CurrentST = CurrentVertexData.ST;
                CurrentST.x = CurrentST.x / TextureWidth / 32;
                CurrentST.y = CurrentST.y / TextureHeight / 32;
                UVs[VertexIndex] = CurrentST;

                CurrentVertexData.UVsCalculated = true;
            }
        }
    }

