                                        NewCommandInstance.Parameters.Add(TagParameter);

                                        //Debug.Log($"Parameter added to {InAIList.Name} in {CurrentCommand.Name}: {TagParameter.TagID}");
                                    }
                                    break;
                                case "Objective":
                                    int ObjectiveIndex = Reader.ReadByte();
                                    NewCommandInstance.Parameters.Add(Objectives.Find(x => x.ID == ObjectiveIndex));

                                    //Debug.Log($"Parameter added to {InAIList.Name} in {Command.Name}: {ObjectiveParameter.DisplayText?.en}");
                                    break;
                                case "Stage":
                                    int StageID = Reader.ReadByte();
                                    Stage StageParameter = DataHolder.Stages.Find(x => x.ID == StageID);

                                    NewCommandInstance.Parameters.Add(StageParameter);
                                    //Debug.Log($"Parameter added to {InAIList.Name} in {Command.Name}: {StageParameter.Name}");
                                    break;
                                case "Body":
                                    NewCommandInstance.Parameters.Add(DataHolder.CharacterDataList[Reader.ReadByte()]);

                                    //Debug.Log($"Parameter added to {InAIList.Name} in {Command.Name}: {BodyData.FileName}");
                                    break;
                                case "Head":
                                    int HeadModelNumber = Reader.ReadByte();

                                    if (HeadModelNumber == 0xFF)
                                    {
                                        NewCommandInstance.Parameters.Add(DataHolder.RandomHeadData);
                                        //Debug.Log($"Parameter added to {InAIList.Name} in {Command.Name}: {HeadData.FileName}");
                                    }
                                    else
                                    {
                                        NewCommandInstance.Parameters.Add(DataHolder.CharacterDataList[HeadModelNumber]);
                                    }
                                    break;
                                case "LanguageString":
                                    NewCommandInstance.Parameters.Add(ReadLanguageString(Reader.ReadInt16()));

                                    //Debug.Log($"Parameter added to {InAIList.Name} in {Command.Name}: {LanguageStringParameter?.en}");
                                    break;
                                case "SoundEffect":
                                    ushort SoundEffectNumber = Reader.ReadUInt16();

                                    int SoundEffectParameter = (int)SoundEffectNumber;

                                    /*ushort SoundEffectID = 0;
                                    bool IsMP3 = false;
                                    SoundEffectInstance SoundEffectParameter = new();

