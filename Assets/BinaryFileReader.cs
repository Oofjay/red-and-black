public class TextureData
{
    public byte[] RawTextureData;
    public byte[] UnityTextureData;

    public bool HasCustomDetailLevels; // Whether the detail level images are included in the file. If not, they're generated by the game
    public int DetailLevels;
    public int Width;
    public int Height;
    public TexturePixelFormat PixelFormat;

    public int[] LookupTable;
    public int NumberOfColours;

    public short[] Palette;

    // Returns the amount of pixels in the texture.
    public int SizeAsPixels 
    { 
        get
        {
            return Width * Height;
        } 
    }

    // Returns the texture size as the total amount of separate colour/alpha values. Equals SizeAsPixels times the number of channels.
    // This is used for functions that only operate on the RGB and intensity values, but not yet on the (possible) 1-bit alpha channels.
    public int SizeAsChannelsWithout1BitAlpha
    {
        get
        {
            return Width * Height * GetNumberOfChannels();
        }
    }

    // Same as SizeAsChannels, but including the 1-bit alpha channels. This is used to reserve enough room in the raw texture data for
    // all channels, including the 1-bit alpha channel.
    public int SizeAsChannelsWith1BitAlpha
    {
        get
        {
            return Has1BitAlphaChannel() ? Width * Height * (GetNumberOfChannels() + 1) : Width * Height * GetNumberOfChannels();
        }
    }

    // How many channels (colours, intensity, alpha) does the texture format have? (excluding 1-bit alpha channels)
    public int GetNumberOfChannels()
    {
        switch (PixelFormat)
        {
            case TexturePixelFormat.RGBA32:
                return 4;
            case TexturePixelFormat.RGBA16:
            case TexturePixelFormat.RGBA16_CI8:
            case TexturePixelFormat.RGBA16_CI4:
            case TexturePixelFormat.RGB24:
            case TexturePixelFormat.RGB15:
                return 3;
            case TexturePixelFormat.IA16:
            case TexturePixelFormat.IA8:
            case TexturePixelFormat.IA16_CI8:
            case TexturePixelFormat.IA16_CI4:
                return 2;
            default:
                return 1;
        }
    }

    // How many channels (colours, intensity, alpha) does the texture format have? (including 1-bit alpha channels)
    public int GetNumberOfChannelsWith1BitAlpha()
    {
        switch (PixelFormat)
        {
            case TexturePixelFormat.RGBA32:
            case TexturePixelFormat.RGBA16:
            case TexturePixelFormat.RGBA16_CI8:
            case TexturePixelFormat.RGBA16_CI4:
                return 4;
            case TexturePixelFormat.RGB24:
            case TexturePixelFormat.RGB15:
                return 3;
            case TexturePixelFormat.IA16:
            case TexturePixelFormat.IA8:
            case TexturePixelFormat.IA4:
            case TexturePixelFormat.IA16_CI8:
            case TexturePixelFormat.IA16_CI4:
                return 2;
            default:
                return 1;
        }
    }

    // Some texture formats have a 1-bit alpha channel tacked on at the end. Returns whether the texture has a 1-bit alpha channel.
    public bool Has1BitAlphaChannel()
    {
        switch (PixelFormat)
        {
            case TexturePixelFormat.RGBA16:
            case TexturePixelFormat.RGBA16_CI8:
            case TexturePixelFormat.RGBA16_CI4:
            case TexturePixelFormat.IA4:
                return true;
            default:
                return false;
        }
    }

    // Converts the PD texture format to Unity's format. The formats without alpha will use RGB24, and with alpha will use RGBA32.
    public TextureFormat GetUnityTextureFormat()
    {
        switch (PixelFormat)
        {
            case TexturePixelFormat.RGBA32:
            case TexturePixelFormat.RGBA16:
            case TexturePixelFormat.IA16:
            case TexturePixelFormat.IA8:
            case TexturePixelFormat.IA4:
            case TexturePixelFormat.RGBA16_CI8:
            case TexturePixelFormat.RGBA16_CI4:
            case TexturePixelFormat.IA16_CI8:
            case TexturePixelFormat.IA16_CI4:
                return TextureFormat.RGBA32;
            default:
                return TextureFormat.RGB24;
        }
    }

    // This is used to get the size of each channel, which is important for blurring and Huffman compression.
    public int GetChannelSize()
    {
        switch (PixelFormat)
        {
            case TexturePixelFormat.RGBA32:
            case TexturePixelFormat.RGB24:
            case TexturePixelFormat.IA16:
            case TexturePixelFormat.I8:
            case TexturePixelFormat.RGBA16_CI8:
            case TexturePixelFormat.IA16_CI8:
                return 256;
            case TexturePixelFormat.RGBA16:
            case TexturePixelFormat.RGB15:
                return 32;
            case TexturePixelFormat.IA8:
            case TexturePixelFormat.I4:
            case TexturePixelFormat.RGBA16_CI4:
            case TexturePixelFormat.IA16_CI4:
                return 16;
            default:
                return 8;
        }
    }

    // How many bits does each pixel contain? This is important for building a texture lookup table.
    public int GetBitsPerPixel()
    {
        switch (PixelFormat)
        {
            case TexturePixelFormat.RGBA32:
                return 32;
            case TexturePixelFormat.RGB24:
                return 24;
            case TexturePixelFormat.RGBA16:
            case TexturePixelFormat.IA16:
            case TexturePixelFormat.RGBA16_CI8:
            case TexturePixelFormat.RGBA16_CI4:
            case TexturePixelFormat.IA16_CI8:
            case TexturePixelFormat.IA16_CI4:
                return 16;
            case TexturePixelFormat.RGB15:
                return 15;
            case TexturePixelFormat.IA8:
            case TexturePixelFormat.I8:
                return 8;
            default:
                return 4;
        }
    }

    // Generates a byte array with enough size to fit all the texture data. If applicable, calculates enough room for each mip (detail level).
    public byte[] GenerateRawTextureData()
    {
        int TextureSize = 0;
        int CurrentWidth = Width;
        int CurrentHeight = Height;

        for (int i = 0; i <= DetailLevels; ++i)
        {
            TextureSize += CurrentWidth * CurrentHeight * GetNumberOfChannelsWith1BitAlpha();

            // Each mip has half the size of the previous mip
            CurrentWidth /= 2;
            CurrentHeight /= 2;
        }

        return new byte[TextureSize];
    }
}

