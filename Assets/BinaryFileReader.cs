                                        case 16:
                                            shortnumber = Reader.ReadInt16();
                                            Writer.Write(shortnumber);
                                            break;
                                        case 32:
                                            intnumber = Reader.ReadInt32();
                                            Writer.Write(intnumber);
                                            break;
                                        default:
                                            break;
                                    }
                                    break;
                                case "BitFlag":
                                    BitFlagCollection BitFlags = new();

                                    string BitFlagType = CurrentParameter.ConstantName;

                                    if (BitFlagType == "VARIABLE")
                                    {
                                        intnumber = Reader.ReadInt32();
                                        Writer.Write(intnumber);
                                        break;
                                    }
                                    else if (BitFlagType == "STAGEFLAG")
                                    {
                                        intnumber = Reader.ReadInt32();
                                        Writer.Write(intnumber);
                                    }
                                    else if (BitFlagType == "LOCKFLAG")
                                    {
                                        bytenumber = Reader.ReadByte();
                                        Writer.Write(bytenumber);
                                    }
                                    else
                                    {
                                        int Bits;
                                        int BitFlagSize = GameBitFlagHolder.BitFlagSizes[BitFlagType];

                                        switch (BitFlagSize)
                                        {
                                            case 8:
                                                bytenumber = Reader.ReadByte();
                                                Writer.Write(bytenumber);
                                                break;
                                            case 16:
                                                shortnumber = Reader.ReadInt16();
                                                Writer.Write(shortnumber);
                                                break;
                                            case 32:
                                                intnumber = Reader.ReadInt32();
                                                Writer.Write(intnumber);
                                                break;
                                            default:
                                                Bits = 0;
                                                break;
                                        }

                                    }
                                    break;
                                case "null":
                                    bytenumber = Reader.ReadByte();
                                    Writer.Write(bytenumber);
                                    break;
                                default:
                                    Debug.LogError($"Syntax error: Parameter {CurrentParameter.ClassType} not recognized at: {Reader.ReadOffset:X}");
                                    break;
                            }
                        }
                    }

                    ReturnFromPointer();
                }
            }

            ReturnFromPointer();
        }

        Reader.Dispose();
        MainFileStream.Dispose();

        Writer.Dispose();
        WriteStream.Dispose();
    }

