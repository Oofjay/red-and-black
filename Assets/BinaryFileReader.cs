                                    NewCommandInstance.Parameters.Add(SoundEffectParameter);

                                    //Debug.Log($"Parameter added to {NewAIList.ID:X} in {CurrentCommand.Name}: {DataHolder.SoundEffects.Find(x => x.ID == SoundEffectID)}");
                                    break;
                                case "MusicTrack":
                                    NewCommandInstance.Parameters.Add(DataHolder.MusicTracks[Reader.ReadByte()]);

                                    //Debug.Log($"Parameter added to {InAIList.Name} in {Command.Name}: {DataHolder.MusicTracks.Find(x => x.Name == MusicTrackName).Name}");
                                    break;
                                case "Portal":
                                    NewCommandInstance.Parameters.Add(DataHolder.Portals[Reader.ReadInt16()]);

                                    //Debug.Log($"Parameter added to {InAIList.Name} in {Command.Name}: Portal");
                                    break;
                                case "Quip":
                                    NewCommandInstance.Parameters.Add((int)Reader.ReadByte());

                                    //Debug.Log($"Parameter added to {InAIList.Name} in {Command.Name}: {int.Parse(Quip[2..], NumberStyles.HexNumber)}");
                                    break;
                                case "SpecialSoundBank":
                                    NewCommandInstance.Parameters.Add((int)Reader.ReadByte());

                                    //Debug.Log($"Parameter added to {InAIList.Name} in {Command.Name}: {int.Parse(SoundBankProperty[2..], NumberStyles.HexNumber)}");
                                    break;
                                case "Constant":
